#!/usr/bin/env python3
"""Regenerate the GENERATED block of _shared/family_registry.md from disk.

Authority: each skill's own sovereign-header `families:` declaration is the
source of truth for membership. This script never invents a family and never
edits the CURATED block below the marker -- it rewrites only the generated
table, so hand-written propagation patterns survive regeneration.

Run from the repo root:  python operads/skills/_shared/regen_family_registry.py
Exit 1 if the registry changed (use in a gate to catch drift).
"""

from __future__ import annotations

import collections
import pathlib
import re
import sys

# Canonical skill root (mirrored to .claude/.codex/.grok via sync_cross_host_skills).
SKILLS = pathlib.Path("operads/skills")
if not SKILLS.is_dir():
    SKILLS = pathlib.Path(".claude/skills")
REGISTRY = SKILLS / "_shared" / "family_registry.md"
MARKER = "<!-- END GENERATED -->"


def harvest() -> tuple[dict[str, list[str]], list[str]]:
    families: dict[str, list[str]] = collections.defaultdict(list)
    orphans: list[str] = []
    for path in sorted(SKILLS.glob("*/SKILL.md")):
        head = path.read_text(encoding="utf-8", errors="replace")[:1500]
        name = path.parent.name
        listed = re.search(r"families:\s*\[([^\]]*)\]", head)
        single = re.search(r"family:\s*([A-Za-z0-9_-]+)", head)
        if listed:
            for fam in (f.strip() for f in listed.group(1).split(",")):
                if fam:
                    families[fam].append(name)
        elif single:
            families[single.group(1)].append(name)
        else:
            orphans.append(name)
    return families, orphans


def render(families: dict[str, list[str]], orphans: list[str]) -> str:
    lines = [
        "<!-- GENERATED by regen_family_registry.py -- do not hand-edit above the marker. -->",
        "",
        "# Skill Family Registry",
        "",
        "## Declared Families (from sovereign headers)",
        "",
        "| Family | N | Members |",
        "| --- | --- | --- |",
    ]
    for fam in sorted(families):
        members = sorted(families[fam])
        lines.append(f"| `{fam}` | {len(members)} | {', '.join(members)} |")
    lines.extend(
        [
            "",
            "## Skills With No Family Declaration",
            "",
            "These are invisible to family propagation. Either add a `families:` field",
            "to the sovereign header or accept that no rule will ever propagate to them.",
            "",
        ]
    )
    lines.extend([f"- `{name}`" for name in sorted(orphans)] or ["- (none)"])
    lines.extend(["", MARKER, ""])
    return "\n".join(lines)


def main() -> int:
    if not SKILLS.is_dir():
        print(f"error: {SKILLS} not found -- run from the repo root", file=sys.stderr)
        return 2
    families, orphans = harvest()
    generated = render(families, orphans)

    curated = ""
    if REGISTRY.exists():
        existing = REGISTRY.read_text(encoding="utf-8")
        if MARKER in existing:
            curated = existing.split(MARKER, 1)[1].lstrip("\n")
        else:
            print("warning: marker missing; curated content preserved verbatim below")
            curated = existing

    new = generated + curated
    changed = (not REGISTRY.exists()) or REGISTRY.read_text(encoding="utf-8") != new
    REGISTRY.write_text(new, encoding="utf-8")
    print(
        f"{'UPDATED' if changed else 'unchanged'}: {REGISTRY} "
        f"({len(families)} families, {len(orphans)} orphans)"
    )
    return 1 if changed else 0


if __name__ == "__main__":
    raise SystemExit(main())
