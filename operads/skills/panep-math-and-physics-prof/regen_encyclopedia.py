def _strip_comment(value: str) -> str:
    """Strip a trailing ' # ...' comment that is outside any quotes."""
    in_q: str | None = None
    for i, ch in enumerate(value):
        if in_q:
            if ch == in_q:
                in_q = None
        elif ch in "\"'":
            in_q = ch
        elif ch == "#" and (i == 0 or value[i - 1] in " \t"):
            return value[:i].rstrip()
    return value


def _unquote(value: str) -> str:
    value = value.strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        return value[1:-1]
    return value


def _parse_inline_list(inner: str) -> list[str]:
    inner = inner.strip()
    if not inner:
        return []
    if '"' in inner or "'" in inner:
        return [m.group(1) or m.group(2) for m in re.finditer(r'"([^"]*)"|\'([^\']*)\'', inner)]
    return [tok.strip() for tok in inner.split(",") if tok.strip()]


def parse_frontmatter(text: str) -> tuple[dict, str, list[str]]:
    """Parse the restricted flat-YAML frontmatter. Returns (fm, body, errors)."""
    errors: list[str] = []
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        return {}, text, ["missing frontmatter opening '---'"]
    fm: dict = {}
    i = 1
    current_list: str | None = None
    while i < len(lines):
        raw = lines[i]
        if raw.strip() == "---":
            i += 1
            break
        stripped = _strip_comment(raw)
        if not stripped.strip():
            i += 1
            continue
        block_item = re.match(r"^\s+-\s+(.*)$", stripped)
        if block_item and current_list:
            fm[current_list].append(_unquote(block_item.group(1)))
            i += 1
            continue
        kv = re.match(r"^([A-Za-z_][A-Za-z0-9_]*):\s*(.*)$", stripped)
        if not kv:
            errors.append(f"unparseable frontmatter line {i + 1}: {raw!r}")
            i += 1
            continue
        key, value = kv.group(1), kv.group(2).strip()
        current_list = None
        if value == "":
            fm[key] = []
            current_list = key
        elif value.startswith("[") and value.endswith("]"):
            fm[key] = _parse_inline_list(value[1:-1])
        else:
            fm[key] = _unquote(value)
        i += 1
    else:
        errors.append("frontmatter never closed with '---'")
    body = "\n".join(lines[i:])
    return fm, body, errors


