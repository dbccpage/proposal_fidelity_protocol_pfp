_SETEXT_H2_RE = re.compile(r"(?m)^(?![#|>\s*+-])([^\n]+?)[ \t]*\n-{3,}[ \t]*$")


_FENCE_RE = re.compile(r"(?ms)^(?P<f>```+|~~~+)[^\n]*\n.*?^(?P=f)[ \t]*$")


def _blank_fenced_blocks(body: str) -> str:
    """Blank out fenced code blocks, preserving line count.

    Section detection must not see headings that live inside a fenced example.
    Without this, a document whose ONLY "Statement"/"Provenance" headings sit
    inside a ``` block satisfies the V5 required-section check -- a validation
    bypass introduced with the setext normalization and reproduced 2026-07-28
    (Codex review of PR #1558). Newlines are preserved so any line numbers
    derived from this body elsewhere remain correct.
    """
    return _FENCE_RE.sub(lambda m: "\n" * m.group(0).count("\n"), body)


def _section_content(body: str, heading: str) -> str | None:
    body = _blank_fenced_blocks(body)
    body = _SETEXT_H2_RE.sub(r"## \1", body)
    m = re.search(rf"(?m)^## {re.escape(heading)}\s*$", body)
    if not m:
        return None
    rest = body[m.end() :]
    nxt = re.search(r"(?m)^## ", rest)
    return rest[: nxt.start()] if nxt else rest


def load_and_validate() -> tuple[list[dict], list[str], list[str]]:
    """Returns (entries, errors, warnings)."""
    errors: list[str] = []
    warnings: list[str] = []
    entries: list[dict] = []
    if not ENTRIES_DIR.exists():
        return entries, errors, warnings

    files = sorted(ENTRIES_DIR.glob("*/*.md"))
    stray = [p for p in sorted(ENTRIES_DIR.rglob("*.md")) if p not in files]
    for p in stray:
        errors.append(f"{p}: entries must sit exactly one layer-dir deep")

    for path in files:
        rel = path.relative_to(REPO_ROOT).as_posix()
        fm, body, fm_errors = parse_frontmatter(path.read_text(encoding="utf-8"))
        for e in fm_errors:
            errors.append(f"{rel}: {e}")
        for field in LIST_FIELDS:
            if field in fm and isinstance(fm[field], str):
                fm[field] = [fm[field]] if fm[field] else []
        entries.append({"path": path, "rel": rel, "fm": fm, "body": body})

    by_id: dict[str, str] = {}
    alias_owner: dict[str, str] = {}
    for ent in entries:
        rel, fm, body = ent["rel"], ent["fm"], ent["body"]
        eid = fm.get("id", "")
        path_name = ent["path"].name

        # V1 -- id format, uniqueness, filename agreement, lowercase
        if not _ID_RE.match(eid):
            errors.append(f"{rel}: V1 id {eid!r} does not match ENC-NNNN")
        elif eid in by_id:
            errors.append(f"{rel}: V1 duplicate id {eid} (also {by_id[eid]})")
        else:
            by_id[eid] = rel
        if path_name != path_name.lower():
            errors.append(f"{rel}: V1 filename must be lowercase")
        if _ID_RE.match(eid) and not path_name.startswith(f"enc-{eid[4:]}-"):
            errors.append(f"{rel}: V1 filename prefix must be 'enc-{eid[4:]}-'")

        # V3 -- enums (+ layer dir agreement)
        layer_dir = ent["path"].parent.name
        checks = [
            ("kind", fm.get("kind"), KINDS),
            ("status", fm.get("status"), STATUSES),
            ("layer", fm.get("layer"), LAYERS),
            ("lean_status", fm.get("lean_status"), LEAN_STATUSES),
            ("migration", fm.get("migration"), MIGRATION_STATES),
        ]
        for field, value, allowed in checks:
            if value not in allowed:
                errors.append(f"{rel}: V3 {field}={value!r} not in {sorted(allowed)}")
        for field, value, allowed in [
            ("tower_level", fm.get("tower_level", "null"), TOWER_LEVELS),
            ("primitive", fm.get("primitive", "null"), PRIMITIVES),
        ]:
            if value not in allowed:
                errors.append(f"{rel}: V3 {field}={value!r} not in {sorted(allowed)}")
        if layer_dir in LAYERS and fm.get("layer") in LAYERS and fm["layer"] != layer_dir:
            errors.append(f"{rel}: V3 layer={fm['layer']!r} but file sits in entries/{layer_dir}/")
        if not fm.get("name"):
            errors.append(f"{rel}: V3 missing name")

        # V2 -- alias namespace + corpus-wide uniqueness
        for alias in fm.get("aliases", []):
            ns = alias.split(":", 1)[0] if ":" in alias else ""
            if ns not in ALIAS_NAMESPACES:
                errors.append(
                    f"{rel}: V2 alias {alias!r} lacks a known namespace {sorted(ALIAS_NAMESPACES)}"
                )
            if alias in alias_owner:
                errors.append(f"{rel}: V2 alias collision {alias!r} (also {alias_owner[alias]})")
            else:
                alias_owner[alias] = rel

        # V5 -- required headings
        for heading in ("Statement", "Provenance"):
            if _section_content(body, heading) is None:
                errors.append(f"{rel}: V5 missing required section '## {heading}'")
        stmt = _section_content(body, "Statement")
        if stmt is not None and not stmt.strip():
            errors.append(f"{rel}: V5 '## Statement' is empty")

        # V6 -- status coherence
        if fm.get("status") == "CONDITIONAL" and not fm.get("conditional_on"):
            errors.append(f"{rel}: V6 status CONDITIONAL requires nonempty conditional_on")
        if fm.get("status") in PROVED_STATUSES:
            proof = _section_content(body, "Proof") or _section_content(body, "Proof Pointer")
            if proof is None or not proof.strip():
                errors.append(
                    f"{rel}: V6 status {fm['status']} requires a nonempty '## Proof' or '## Proof Pointer' section"
                )

    # V4 -- uses + wikilinks resolve
    for ent in entries:
        for dep in ent["fm"].get("uses", []):
            if dep not in by_id:
                errors.append(f"{ent['rel']}: V4 uses {dep!r} does not resolve")
        for link in _WIKILINK_RE.findall(ent["body"]):
            if link not in by_id:
                errors.append(f"{ent['rel']}: V4 wikilink [[{link}]] does not resolve")

    # V7 -- pl: refs exist in the global proof-ledger series. Dated ledgers are
    # continuations (e.g. proof_ledger_20260610.md: "entries there remain live;
    # not duplicated here"), so existence is checked against the union of all
    # dated files; orphan warnings stay scoped to the latest file (the
    # new-obligations signal consumed by the work-queue sync).
    ledgers = sorted(RESEARCH_DIR.glob("proof_ledger_*.md"))
    ledger_ids: set[str] = set()
    latest_ledger_ids: set[str] = set()
    if ledgers:
        for lf in ledgers:
            ledger_ids |= set(_PL_ID_RE.findall(lf.read_text(encoding="utf-8")))
        latest_ledger_ids = set(_PL_ID_RE.findall(ledgers[-1].read_text(encoding="utf-8")))
    referenced_pl: set[str] = set()
    for ent in entries:
        pl_refs = [a for a in ent["fm"].get("lean_refs", []) if a.startswith("pl:")]
        pl_refs += [a for a in ent["fm"].get("aliases", []) if a.startswith("pl:")]
        for ref in pl_refs:
            pl_id = ref.split(":", 1)[1]
            referenced_pl.add(pl_id)
            if ledgers and pl_id not in ledger_ids:
                errors.append(
                    f"{ent['rel']}: V7 {ref!r} not found in the proof-ledger "
                    f"series ({', '.join(lf.name for lf in ledgers)})"
                )
    for orphan in sorted(latest_ledger_ids - referenced_pl):
        warnings.append(f"V7 orphan: ledger id {orphan} has no encyclopedia entry yet")

    # V8 -- dependency cycles (report, don't fail)
    graph = {
        e["fm"].get("id"): [d for d in e["fm"].get("uses", []) if d in by_id]
        for e in entries
        if e["fm"].get("id") in by_id
    }
    state: dict[str, int] = {}

    def visit(node: str, stack: list[str]) -> None:
        state[node] = 1
        for dep in graph.get(node, []):
            if state.get(dep) == 1:
                cyc = stack[stack.index(dep) :] + [dep] if dep in stack else [node, dep]
                warnings.append("V8 dependency cycle: " + " -> ".join(cyc))
            elif state.get(dep, 0) == 0:
                visit(dep, stack + [dep])
        state[node] = 2

    for node in sorted(graph):
        if state.get(node, 0) == 0:
            visit(node, [node])

    return entries, errors, warnings


