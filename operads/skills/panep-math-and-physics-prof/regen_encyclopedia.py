def _is_programme_overview(rel_path: str) -> bool:
    """Is this manuscript a programme's own overview rather than a paper?

    A programme folder matches the paper-id grammar, so its overview document
    (`published/000_witnessed_difference/000_witnessed_difference.md`) derives
    the same id as the paper folder beside it (`000_wd0_.../`). Both then wrote
    to one manifest and the last one won.

    The test is DEPTH, not name: a paper is `published/<programme>/<paper>/x.md`
    (three parts), a programme overview is `published/<programme>/x.md` (two).
    Comparing stem to parent name would match every canonical paper too --
    `002_m_compatible.../002_m_compatible....md` -- and skip the whole corpus.
    """
    parts = Path(rel_path).as_posix().split("/")
    try:
        below = parts[parts.index("published") + 1 :]
    except ValueError:
        return False
    return len(below) == 2


def _canonical_pid(pid: str) -> str:
    if pid.lower().startswith("qm_"):
        return f"QM_{pid[3:]}"
    return pid


def _qualified_pid(pid: str, rel_path: str) -> str:
    """Qualify a paper id, preserving nested CODA/GTOC as the `gg` family."""
    pid = _canonical_pid(pid)
    parts = Path(rel_path).as_posix().split("/")
    try:
        below = parts[parts.index("published") + 1 :]
    except (ValueError, IndexError):
        return pid
    if below[:2] == ["001_coda", "gtoc"]:
        return f"gg{pid}"
    mnemonic = _PROGRAMME_MNEMONICS.get(below[0]) if below else None
    return f"{mnemonic}{pid}" if mnemonic else pid


_SOURCE_PAPER_TOKEN = re.compile(r"^([0-9]{3}[a-z]?|qm_[0-9]{3}[a-z]?)_", re.IGNORECASE)


_COMPANION_SUFFIXES = ("_change_log", "_claim_ledger", "_update_packet", "_tables_of_contents")


def _is_companion_file(rel_path: str) -> bool:
    """True for a paper's companion document, never a manifest source.

    A change log / claim ledger / update packet is ABOUT a paper; it is not the
    manuscript. Companions were entering the candidate set and, where the
    manuscript itself carries a non-numeric `Paper ID` (so the extractor skips
    it), a companion became the SOLE candidate -- producing a manifest sourced
    from the change log with zero extracted rows, reported as
    `Rows: 0 | undispositioned: 0`. That is a false green: an unextracted paper
    is indistinguishable from a fully-dispositioned one.

    Found via the Codex review of PR #1558 (extraction_paper_er007 swapped
    symbol_game_000.md -> symbol_game_000_change_log.md and dropped its one
    Conjecture row). Pre-existing extractor behaviour, exposed once regen ran
    again after being corpus-wide broken.
    """
    return Path(rel_path).stem.endswith(_COMPANION_SUFFIXES)


def _source_paper_pid(source: str) -> str | None:
    """Derive a collision-free paper id from a fully qualified source path."""
    source_path = source.split()[0].strip("`\"'.,;") if source.split() else ""
    token = Path(source_path).name
    match = _SOURCE_PAPER_TOKEN.match(token)
    if match is None:
        return None
    return _qualified_pid(match.group(1), source_path)


