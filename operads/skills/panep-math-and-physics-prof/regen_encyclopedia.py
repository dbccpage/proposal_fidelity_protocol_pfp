def _parse_stmt(line: str) -> tuple[str, str, str] | None:
    """Return (kind, label, name) for a statement line, else None.

    Order matters: the original spine patterns run first so existing manifest
    keys (and therefore preserved dispositions) stay byte-stable.
    """
    stripped = re.sub(r"^(?:>\s*)+", "", line)  # blockquote markers
    is_heading = stripped.startswith("#")
    stripped = re.sub(r"^#{1,6}\s+", "", stripped)
    stripped = _LEAD_NUM_RE.sub("", stripped, count=1)  # leading section number
    if stripped.startswith("**"):
        m = _STMT_BOLD_RE.match(stripped)
        if m:
            return m.group(1), (m.group(2) or "").strip(), (m.group(3) or "").strip()
        m = _STMT_BOLD_TAGGED_RE.match(stripped)
        if m:
            return m.group(1), (m.group(2) or "").strip(), (m.group(3) or "").strip()
        m = _STMT_LOOSE_RE.match(stripped)
        if m:
            return m.group(1), m.group(2).rstrip(".,;:"), ""
        return None
    if is_heading:
        heading_text = re.sub(r"^#+\s+", "", stripped)
        mgt = _GT_ID_HEADING_RE.match(heading_text)
        if mgt is not None:
            label = f"{mgt.group(1)}-{mgt.group(2)}"
            kind = _GT_ID_KIND.get(mgt.group(2)[0], "Theorem")
            return kind, label, (mgt.group(3) or "").strip()
        m = _STMT_HEADING_RE.match(stripped)
        if m and m.group(3) is not None:  # paren-named — the original spine form
            return m.group(1), (m.group(2) or "").strip(), (m.group(3) or "").strip()
        md = _STMT_HEADING_DASH_RE.match(stripped)
        if md:
            return md.group(1), (md.group(2) or "").strip(), (md.group(3) or "").strip()
        if m:
            return m.group(1), (m.group(2) or "").strip(), (m.group(3) or "").strip()
    return None


def _scan_gtmur_math_spine_sections(spine: Path) -> list[dict]:
    rows: list[dict] = []
    lines = spine.read_text(encoding="utf-8").splitlines()
    seen_keys: dict[tuple, int] = {}
    for heading, kind, label, name, tag in _GTMUR_SPINE_SECTION_MAP:
        for lineno, line in enumerate(lines, 1):
            if line.startswith(heading):
                key = (kind, label, name)
                seen_keys[key] = seen_keys.get(key, 0) + 1
                rows.append(
                    {
                        "key": f"{kind}::{label}::{name}::{seen_keys[key]}",
                        "line": lineno,
                        "section": re.sub(r"^#+\s*", "", line).strip(),
                        "kind": kind,
                        "label": label,
                        "name": name,
                        "tag": tag,
                    }
                )
                break
    return rows


def scan_spine_statements(spine: Path) -> list[dict]:
    if _is_gtmur_math_spine(spine):
        return _scan_gtmur_math_spine_sections(spine)
    rows: list[dict] = []
    section = ""
    seen_keys: dict[tuple, int] = {}
    for lineno, line in enumerate(spine.read_text(encoding="utf-8").splitlines(), 1):
        if re.match(r"^#{2,3} ", line):
            section = re.sub(r"^#+\s*", "", line).strip()
        if not (
            line.startswith("**")
            or line.startswith("#")
            or line.lstrip("> ").startswith(("**", "#"))
        ):
            continue
        parsed = _parse_stmt(line)
        if _is_gtmur_theorem_ledger(spine) and parsed == ("Definition", "s", ""):
            continue
        if parsed is None or (
            _GT_ID_HEADING_RE.match(re.sub(r"^#+\s+", "", re.sub(r"^(?:>\s*)+", "", line)).strip())
            and not _is_gtmur_theorem_ledger(spine)
        ):
            continue
        kind, label, name = parsed
        label = label.rstrip(".").strip()
        tag = _STATUS_TAG_RE.search(line)
        key = (kind, label, name)
        seen_keys[key] = seen_keys.get(key, 0) + 1
        rows.append(
            {
                "key": f"{kind}::{label}::{name}::{seen_keys[key]}",
                "line": lineno,
                "section": section,
                "kind": kind,
                "label": label or "—",
                "name": name or "—",
                "tag": tag.group(1) if tag else "—",
            }
        )
    return rows


def _load_existing_dispositions(path: Path) -> dict[str, str]:
    if not path.exists():
        return {}
    dispositions: dict[str, str] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if (
            len(cells) == 8
            and len(cells[0]) > 2
            and cells[0].startswith("`")
            and cells[0].endswith("`")
        ):
            dispositions[cells[0][1:-1]] = cells[7]
    return dispositions


def _manifest_source(path: Path) -> str:
    if not path.exists():
        return ""
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("Source: `") and "`" in line[9:]:
            return _canonical_manifest_source(line.split("`", 2)[1])
    return ""


def _canonical_manifest_source(source: str) -> str:
    source = source.strip().strip("`").replace("\\", "/")
    for prefix in ("omega_engine/research/", "research/"):
        if source.startswith(prefix):
            return source[len(prefix) :]
    return source


def _load_dispositions_for_same_source(source: Path, manifest_path: Path) -> dict[str, str]:
    source_key = _canonical_manifest_source(source.relative_to(REPO_ROOT).as_posix())
    dispositions: dict[str, str] = {}
    for candidate in sorted(MANIFESTS_DIR.glob("*.md")):
        if _manifest_source(candidate) != source_key:
            continue
        for key, value in _load_existing_dispositions(candidate).items():
            if value and value not in {"—", "-"}:
                dispositions.setdefault(key, value)
    for key, value in _load_existing_dispositions(manifest_path).items():
        if value and value not in {"—", "-"}:
            dispositions[key] = value
    return dispositions


