def emit_manifest(source: Path, manifest_path: Path, title: str) -> tuple[int, int]:
    _mkdir(MANIFESTS_DIR, parents=True)
    rows = scan_spine_statements(source)
    keep = _load_dispositions_for_same_source(source, manifest_path)
    table_rows = []
    undispositioned = 0
    for r in rows:
        disp = keep.get(r["key"], "").strip()
        if not disp or disp in {"—", "-", ""}:
            disp = "—"
            undispositioned += 1
        table_rows.append(
            [
                f"`{r['key']}`",
                str(r["line"]),
                r["section"],
                r["kind"],
                r["label"],
                r["name"],
                r["tag"],
                disp,
            ]
        )
    lines = (
        [
            "Source: `" + source.relative_to(REPO_ROOT).as_posix() + "`.",
            "Rows are GENERATED (keys + loci refresh on regen); the **disposition**",
            "column is HUMAN — it is preserved across regens by key, never overwritten.",
            "Legal dispositions: `ENC-NNNN` | `doctrine/<file>` | `DUPLICATE-OF ENC-NNNN`",
            "| `HISTORICAL` | `RETIRED`. Parity gate: zero `—` rows and every ENC",
            "disposition pointing at an entry with `migration: VERIFIED`.",
            "",
        ]
        + _table(
            ["key", "line", "section", "kind", "label", "name", "status tag", "disposition"],
            table_rows,
        )
        + [
            "",
            f"Rows: {len(table_rows)} | undispositioned: {undispositioned}",
        ]
    )
    _emit(manifest_path, _doc(title, lines))
    return len(table_rows), undispositioned


