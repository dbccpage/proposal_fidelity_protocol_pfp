"""Build the atlas claim ledger and its one-to-one correspondence with the derivation DAG.

AuthorityEffect: None. This script copies claims; it grades nothing.

Inputs (read only):
  atlas/archive/**/<claim ledger>.md   per-paper claim ledgers, frozen bytes
  atlas/atlas_manuscript_claims.json   claims read from manuscripts that have no usable ledger
  dag/derivations_dag.json             the derivation DAG

Outputs:
  atlas/atlas_claim_ledger.json        typed ledger (source of truth)
  atlas/atlas_claim_ledger.md          rendered ledger
  dag/derivations_dag.json             one node per archive claim, atlas_ledger_id on every derivation node

Run from the repository root:  python dag/build_atlas.py [--check]
--check rebuilds in memory and exits 1 if any output differs or the correspondence is not one to one.
"""
from __future__ import annotations

import glob
import hashlib
import json
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ARCHIVE = "atlas/archive"
LEDGER_JSON = "atlas/atlas_claim_ledger.json"
LEDGER_MD = "atlas/atlas_claim_ledger.md"
PAPER_MD = "atlas/atlas.md"
INDEX_START = "<!-- claim-index:start (generated by dag/build_atlas.py; do not edit by hand) -->"
INDEX_END = "<!-- claim-index:end -->"
MANUSCRIPT_CLAIMS = "atlas/atlas_manuscript_claims.json"
DAG = "dag/derivations_dag.json"

# DAG node kinds that are not derivations: source pins, stated hypotheses, per-paper verdicts.
NON_DERIVATION_KINDS = frozenset({"pinned_source_file", "explicit_assumption_or_obligation", "paper_assessment"})
ARCHIVE_NODE_KIND = "archive_claim"

CLAIM_COL = re.compile(r"^(claim|statement|formal claim|claim statement|manuscript claim|claim summary|"
                       r"current claim|claim and hypotheses|claim \(location\)|claim \(where\)|description)", re.I)
ID_COL = re.compile(r"^(id|claim id|#)$", re.I)
STATUS_COL = re.compile(r"(status|^type|^kind|category|^tag|verdict)", re.I)
EVIDENCE_COL = re.compile(r"(evidence|proof|basis|verification|binding|formali|lean|checked by|support|python scope|home)", re.I)
LIMIT_COL = re.compile(r"(limit|boundary|falsifier|scope|ceiling|remaining action|hypothes)", re.I)
SECTION_COL = re.compile(r"^(section|location)$", re.I)
# The 2026-10-23 harness-extension table is pasted unchanged into many ledgers; it is process text, not a paper claim.
BOILERPLATE_FIRST_CELLS = frozenset({"New research mechanism"})

STATUS_VOCABULARY = ("proved", "mechanized", "computed", "empirical", "definition", "imported",
                     "scope_fence", "not_measured", "withdrawn", "stated")
_RULE = {
    "withdrawn": r"withdr[ae]w|retract|superseded|refuted|refused\]|\bwithdrawn\b",
    "not_measured": r"\bopen\b|conjectur|not[_ ]measured|not[_ ]run\b|unmeasured|not performed|unperformed|aspiration|pending",
    "scope_fence": r"scope[ _]fence|negative boundary|non-?claim|policy rule|boundary\b",
    "definition": r"definition|\bdefined\b|stipulat|convention|contract\b",
    "imported": r"imported|standard|classical|textbook|citation|external",
    "mechanized": r"\blean\b|mechani[sz]ed|kernel[- ]checked|lake build|machine[- ]checked",
    "proved": r"prov(ed|en|e)\b|proof|theorem|lemma|derivation|derived|direct\b",
    "computed": r"pytest|test_|replay|numerical|executable|computed|checked|check\b|regression|receipt|rust test|script|finite",
    "empirical": r"measured|observed|campaign|empirical|recount|editorial",
}
_NEGATED = re.compile(r"\b(no|not|without|never|n/a;?)\s+(new\s+|additional\s+|executable\s+)?(lean|mechani[sz]ed|proof|formal|executable|check|test|derivation|theorem)[a-z]*", re.I)
STATUS_ORDER = ("withdrawn", "not_measured", "scope_fence", "definition", "imported", "mechanized", "proved", "computed", "empirical")
EVIDENCE_ORDER = ("not_measured", "mechanized", "proved", "computed", "empirical", "definition", "imported", "scope_fence")


# Private engine and persona names stay inside atlas/archive/ (frozen bytes). Text copied out of the
# archive uses the repository rename map: Omega -> Core, omega_* -> core_*, Anomalon -> Sentinel.
# File paths keep their real spelling, because they must resolve.
_SCRUB = (
    (re.compile(r"(?<!\\)\bOmega(?=[A-Z_])"), "Core"),
    (re.compile(r"(?<![\\A-Za-z])Omega\b(?![_\\])"), "Core"),
    (re.compile(r"\bomega_(?=(engine|lifts|sweep|core|cosmology))"), "core_"),
    (re.compile(r"(?<=[a-z])Omega(?![a-z])"), "Core"),
    (re.compile(r"Anomalon"), "Sentinel"),
    (re.compile(r"anomalon"), "sentinel"),
    (re.compile(r"ANOMALON"), "SENTINEL"),
    (re.compile(r"[Ww]oland"), "adversary"),
)


def scrub(text):
    if not isinstance(text, str):
        return text
    for pattern, repl in _SCRUB:
        text = pattern.sub(repl, text)
    return text


def sha256(path: str) -> str:
    return hashlib.sha256((ROOT / path).read_bytes()).hexdigest()


def _first(text: str, order: tuple[str, ...]) -> str | None:
    text = _NEGATED.sub(" ", text or "")
    for status in order:
        if re.search(_RULE[status], text, re.I):
            return status
    return None


def classify(status_text: str, evidence_text: str, statement: str) -> str:
    """Coarse status: the source's own status column first, then its evidence text, then the claim wording."""
    return (_first(status_text, STATUS_ORDER) or _first(evidence_text, EVIDENCE_ORDER)
            or _first(statement, EVIDENCE_ORDER) or "stated")


def split_row(line: str) -> list[str]:
    s = line.strip()
    if s.startswith("|"):
        s = s[1:]
    if s.endswith("|") and not s.endswith("\\|"):
        s = s[:-1]
    return [c.strip().replace("\\|", "|") for c in re.split(r"(?<!\\)\|", s)]


def tables(path: str):
    lines = (ROOT / path).read_text(encoding="utf-8").split("\n")
    i = 0
    while i < len(lines):
        if lines[i].lstrip().startswith("|") and i + 1 < len(lines) and re.match(r"^\s*\|?\s*:?-{2,}", lines[i + 1]):
            header, rows, j = split_row(lines[i]), [], i + 2
            while j < len(lines) and lines[j].lstrip().startswith("|"):
                rows.append((j + 1, split_row(lines[j])))
                j += 1
            yield i + 1, header, rows
            i = j
        else:
            i += 1


def column(header: list[str], pattern: re.Pattern, skip: set[int]) -> int | None:
    for k, h in enumerate(header):
        if k not in skip and pattern.search(h.strip("*` ")):
            return k
    return None


def paper_dirs():
    for series, code in (("pfp", "P"), ("non_pfp", "N")):
        for d in sorted(glob.glob(str(ROOT / ARCHIVE / series / "[0-9][0-9][0-9]_*"))):
            yield series, code, os.path.relpath(d, ROOT).replace(os.sep, "/")


def primary_ledgers(paper: str) -> list[str]:
    found = sorted(glob.glob(str(ROOT / paper / "*claim_ledger*.md")))
    if not found:
        found = sorted(glob.glob(str(ROOT / paper / "_support/history/*claim_ledger*.md")))
    return [os.path.relpath(f, ROOT).replace(os.sep, "/") for f in found]


def harvest_ledger(path: str, prefix: str, start: int, excluded: list[dict]) -> list[dict]:
    claims, n, digest = [], start, sha256(path)
    for line, header, rows in tables(path):
        used: set[int] = set()
        id_k = column(header, ID_COL, used)
        if id_k is not None:
            used.add(id_k)
        claim_k = column(header, CLAIM_COL, used)
        if claim_k is None or not rows:
            excluded.append({"path": path, "line": line, "header": header, "rows": len(rows),
                             "reason": "table has no claim column"})
            continue
        if rows[0][1][claim_k if claim_k < len(rows[0][1]) else 0] in BOILERPLATE_FIRST_CELLS:
            excluded.append({"path": path, "line": line, "header": header, "rows": len(rows),
                             "reason": "repeated 2026-10-23 harness-extension table (process text shared by many ledgers)"})
            continue
        used.add(claim_k)
        cols = {}
        for name, pat in (("section", SECTION_COL), ("status", STATUS_COL), ("evidence", EVIDENCE_COL), ("limit", LIMIT_COL)):
            k = column(header, pat, used)
            if k is not None:
                cols[name] = k
                used.add(k)
        for row_line, cells in rows:
            get = lambda k: scrub(cells[k]) if k is not None and k < len(cells) else ""
            statement = get(claim_k)
            if not statement or set(statement) <= set("-—– "):
                continue
            n += 1
            extra = [scrub(f"{header[k]}: {cells[k]}") for k in range(len(cells)) if k not in used and k < len(header) and cells[k]]
            claims.append({
                "atlas_id": f"{prefix}-{n:03d}",
                "local_id": get(id_k) or None,
                "statement": statement,
                "section": get(cols.get("section")) or None,
                "status_text": get(cols.get("status")) or None,
                "evidence_text": get(cols.get("evidence")) or None,
                "limit_text": get(cols.get("limit")) or None,
                "other_text": "; ".join(extra) or None,
                "status": classify(get(cols.get("status")), get(cols.get("evidence")), statement),
                "source": {"path": path, "line": row_line, "sha256": digest, "kind": "claim_ledger"},
            })
    return claims


def archive_claims() -> tuple[list[dict], list[dict], list[dict]]:
    manual = json.loads((ROOT / MANUSCRIPT_CLAIMS).read_text(encoding="utf-8"))
    by_paper = {p["paper"]: p for p in manual["papers"]}
    claims, excluded, papers = [], [], []
    for series, code, paper in paper_dirs():
        number = os.path.basename(paper)[:3]
        prefix = f"ATL-{code}{number}"
        ledgers = primary_ledgers(paper)
        got: list[dict] = []
        for ledger in ledgers:
            got += harvest_ledger(ledger, prefix, len(got), excluded)
        entry = by_paper.get(paper)
        if entry:
            msrc = entry["manuscript"]
            digest = sha256(msrc)
            for c in entry["claims"]:
                got.append({
                    "atlas_id": f"{prefix}-{len(got) + 1:03d}",
                    "local_id": c.get("local_id"),
                    "statement": scrub(c["statement"]),
                    "section": c.get("section"),
                    "status_text": c.get("status_text"),
                    "evidence_text": c.get("evidence_text"),
                    "limit_text": c.get("limit_text"),
                    "other_text": None,
                    "status": c["status"],
                    "source": {"path": msrc, "line": c["line"], "sha256": digest, "kind": "manuscript"},
                })
        for c in got:
            c["paper"] = paper
        papers.append({"paper": paper, "series": series, "number": number, "prefix": prefix,
                       "ledgers": ledgers, "manuscript_claims_from": entry["manuscript"] if entry else None,
                       "claims": len(got)})
        claims += got
    return claims, excluded, papers


def statement_of(node: dict) -> str:
    for key in ("statement", "claim", "title", "assessment"):
        if isinstance(node.get(key), str) and node[key].strip():
            return node[key].strip()
    return ""


