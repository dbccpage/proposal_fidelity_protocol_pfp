//! Additive characters and quadratic Gauss sums over `GF(q)`, valued in an
//! exact cyclotomic field.
//!
//! For `q = p^k`, the canonical additive character is
//! `psi(x) = zeta_p^{Tr(x)}`, with `Tr` the absolute trace to `F_p`. It is
//! realised in `Q(zeta_N)` whenever `p | N`, as `zeta_N^{(N/p) Tr(x)}`.
//!
//! [`verify_character_sum_identities`] checks, exactly, the two identities the
//! Weyl MUB proof reduces to:
//!
//! * every nontrivial linear character sum vanishes:
//!   `sum_x psi(c x) = 0` for every `c != 0`;
//! * every quadratic Gauss sum has squared modulus `q`:
//!   `|sum_x psi(a x^2 + b x)|^2 = q` for every `a != 0` and every `b`.
//!
//! Both statements are basis-independent, since the absolute trace is, so any
//! representation of `GF(q)` gives the same verdict.
//!
//! This replaces six near-identical copies in `core_mub` (`prime_controls`
//! for `p = 7, 11, 13`, and `odd_prime_power_controls` for `q = 25, 27, 49`).

