//! The operad type table: the single place each type's canonical values are written.
//!
//! To change a vocabulary, edit it here, then run `cargo run -p core_operad_canon -- write` from
//! `code/rust` to regenerate the Python and JSON consumers, and update the sources listed for the
//! type in `operads/skill_operad/yaml/operad_types/`.

use crate::{DdcOp, Family, OperadColour, OperadType, Status};

/// Types that Python code uses as an `Enum`, and the class name the generated module gives each.
pub const PYTHON_ENUMS: &[(&str, &str)] = &[
    ("operad_colour", "OperadColour"),
    ("ddc_letter", "DdcLetter"),
    ("hit_disposition", "HitDisposition"),
];

/// Look up a type by its registry id.
pub fn type_by_id(id: &str) -> Option<&'static OperadType> {
    OPERAD_TYPES.iter().find(|entry| entry.id == id)
}

