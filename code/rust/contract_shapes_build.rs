// Shared build-time enforcement of the governance packet contracts.
//
// `include!`d by every crate whose packets are contracted, so the enforcement
// itself has exactly one copy. Two hand-maintained copies of a drift detector
// would be a poor joke.
//
// AuthorityEffect: None.

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

use serde::Deserialize;

#[derive(Debug, Deserialize)]
struct Contract {
    contract_id: String,
    structure: Option<Structure>,
}

#[derive(Debug, Deserialize)]
struct Structure {
    /// Which enforcement engine owns this contract. Python contracts live in
    /// the same directory and are enforced by a pytest gate; skipping them
    /// here by declaration is safer than skipping them by a missing field.
    #[serde(default = "default_language")]
    language: String,
    #[serde(default)]
    rust_crate: String,
    #[serde(default)]
    rust_module: String,
    #[serde(default)]
    rust_type: String,
    #[serde(default)]
    form: String,
    #[serde(default)]
    serde: SerdePolicy,
    #[serde(default)]
    fields: Vec<Field>,
    #[serde(default)]
    variants: Vec<String>,
}

#[derive(Debug, Default, Deserialize)]
struct SerdePolicy {
    #[serde(default)]
    deny_unknown_fields: bool,
}

#[derive(Debug, Deserialize)]
struct Field {
    name: String,
    #[serde(default)]
    #[allow(dead_code)]
    rust_type: String,
}

fn default_language() -> String {
    "rust".to_owned()
}

/// Walk up from the crate directory to the repository root, which is the
/// nearest ancestor holding the governance tree.
fn contracts_dir() -> Option<PathBuf> {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").ok()?);
    let mut cursor: &Path = manifest.as_path();
    loop {
        let primary = cursor
            .join("governance")
            .join("contracts")
            .join("contracts_pfp");
        if primary.is_dir() {
            return Some(primary);
        }
        let fallback = cursor
            .join("governance")
            .join("contracts")
            .join("contracts_packets")
            .join("symbol_game");
        if fallback.is_dir() {
            return Some(fallback);
        }
        let archive = cursor
            .join("governance")
            .join("contracts")
            .join("_archive")
            .join("contracts_pfp");
        if archive.is_dir() {
            return Some(archive);
        }
        cursor = cursor.parent()?;
    }
}

fn fail(message: &str) -> ! {
    // cargo::error surfaces as a build error rather than a silent warning.
    println!("cargo::error={message}");
    std::process::exit(1);
}

const CONTRACT_HEADER: &str = "\
// @generated by build.rs from governance/contracts/\n\
// contracts_pfp/. Do not edit; amend the contract.\n\n";

struct RenderedContracts {
    shapes_body: String,
    tests_body: String,
    enforced: usize,
}

/// Enforce one crate's contracts at that crate's root (`crate::<module>`).
pub fn enforce_packet_contracts(crate_name: &str) {
    let rendered = render_packet_contracts(crate_name, "");
    write_rendered(&rendered);
}

/// Enforce several contract owners into one crate.
///
/// Each pair is `(rust_crate filter, module prefix)`. An empty prefix addresses
/// `crate::<module>`. A prefix such as `epics` addresses `crate::epics::<module>`,
/// which is how `pfp` holds the former epics modules.
pub fn enforce_packet_contracts_grouped(parts: &[(&str, &str)]) {
    println!("cargo::rerun-if-changed=build.rs");
    println!("cargo::rerun-if-changed=../contract_shapes_build.rs");
    let mut shapes_body = String::new();
    let mut tests_body = String::new();
    let mut enforced = 0usize;
    for (crate_name, module_prefix) in parts {
        let rendered = render_packet_contracts(crate_name, module_prefix);
        shapes_body.push_str(&rendered.shapes_body);
        tests_body.push_str(&rendered.tests_body);
        enforced += rendered.enforced;
    }
    write_rendered(&RenderedContracts {
        shapes_body,
        tests_body,
        enforced,
    });
}

fn discover_contract_files(dir: &Path) -> Vec<PathBuf> {
    let mut entries: Vec<PathBuf> = match fs::read_dir(dir) {
        Ok(read) => read
            .filter_map(|e| e.ok())
            .map(|e| e.path())
            .filter(|p| p.to_string_lossy().ends_with(".contract.yaml"))
            .collect(),
        Err(e) => fail(&format!("cannot read {}: {e}", dir.display())),
    };
    entries.sort();

    if entries.is_empty() {
        fail(&format!(
            "no *.contract.yaml files in {} -- a contract directory that \
             declares nothing enforces nothing",
            dir.display()
        ));
    }
    entries
}

fn load_contract_file(path: &Path) -> Contract {
    println!("cargo::rerun-if-changed={}", path.display());
    let text = match fs::read_to_string(path) {
        Ok(text) => text,
        Err(e) => fail(&format!("cannot read {}: {e}", path.display())),
    };
    match serde_yaml::from_str(&text) {
        Ok(contract) => contract,
        Err(e) => fail(&format!("{} is not a valid contract: {e}", path.display())),
    }
}

fn register_unique_contract(
    path: &Path,
    contract_id: &str,
    rust_type: &str,
    by_urn: &mut BTreeMap<String, String>,
    by_type: &mut BTreeMap<String, String>,
) {
    if let Some(previous) = by_urn.insert(contract_id.to_owned(), format!("{}", path.display())) {
        fail(&format!(
            "contract id {} is declared twice: {} and {}",
            contract_id,
            previous,
            path.display()
        ));
    }
    if let Some(previous) = by_type.insert(rust_type.to_owned(), format!("{}", path.display())) {
        fail(&format!(
            "rust type {} is claimed by two contracts: {} and {}",
            rust_type,
            previous,
            path.display()
        ));
    }
}

fn resolve_module_and_stem(module_prefix: &str, module: &str, ty: &str) -> (String, String) {
    let lower = ty.to_lowercase();
    let mod_path = if module_prefix.is_empty() {
        module.to_owned()
    } else if module.is_empty() {
        module_prefix.to_owned()
    } else {
        format!("{module_prefix}::{module}")
    };
    // A merged crate can hold two owners. Prefix the generated function so
    // `Evidence` in the host and `Evidence` in the epics modules do not
    // collide, while a single-owner crate keeps the historical name.
    let fn_stem = if module_prefix.is_empty() {
        lower
    } else {
        format!("{module_prefix}_{lower}")
    };
    (mod_path, fn_stem)
}

fn render_struct_contract(
    path: &Path,
    urn: &str,
    structure: &Structure,
    mod_path: &str,
    fn_stem: &str,
    generated: &mut String,
    generated_tests: &mut String,
) {
    if structure.fields.is_empty() {
        fail(&format!(
            "{} declares form: struct with no fields",
            path.display()
        ));
    }
    let ty = &structure.rust_type;
    let binds = structure
        .fields
        .iter()
        .map(|f| format!("{}: _", f.name))
        .collect::<Vec<_>>()
        .join(", ");
    generated.push_str(&format!(
        "/// Contract {urn}.\n\
         ///\n\
         /// Exhaustive destructure: a field added to `{ty}` without amending the\n\
         /// contract fails to compile here, and a field removed or renamed fails too.\n\
         #[allow(dead_code)]\n\
         fn _contract_shape_{fn_stem}(value: &crate::{mod_path}::{ty}) {{\n    \
         let crate::{mod_path}::{ty} {{ {binds} }} = value;\n}}\n\n",
    ));
    if structure.serde.deny_unknown_fields {
        generated_tests.push_str(&format!(
            "#[test]\n\
             fn contract_{fn_stem}_rejects_undeclared_fields() {{\n    \
             // The contract declares deny_unknown_fields: true. A wire packet\n    \
             // carrying a field the schema never declared must be refused, not\n    \
             // silently ignored -- an ignored field is one a reader believes is\n    \
             // load-bearing while it is inert.\n    \
             // A static string supports packet fields that deliberately borrow\n    \
             // `&'static str`; `from_value` would require DeserializeOwned and\n    \
             // reject those types before this conformance probe could run.\n    \
             let outcome: Result<crate::{mod_path}::{ty}, _> =\n        \
             serde_json::from_str(r#\"{{\"__undeclared_by_contract__\":1}}\"#);\n    \
             let message = match outcome {{\n        \
             Ok(_) => panic!(\n            \
             \"{ty} accepted an undeclared field; contract {urn} requires deny_unknown_fields\"\n        \
             ),\n        \
             Err(e) => e.to_string(),\n    \
             }};\n    \
             assert!(\n        \
             message.contains(\"unknown field\"),\n        \
             \"{ty} rejected the probe for the wrong reason ({{message}}); contract {urn} \\\n         \
             requires deny_unknown_fields, and a rejection caused by a missing required \\\n         \
             field would pass this test while the attribute was absent\"\n    \
             );\n}}\n\n",
        ));
    }
}

fn render_enum_contract(
    path: &Path,
    urn: &str,
    structure: &Structure,
    mod_path: &str,
    fn_stem: &str,
    generated: &mut String,
) {
    if structure.variants.is_empty() {
        fail(&format!(
            "{} declares form: enum with no variants",
            path.display()
        ));
    }
    let ty = &structure.rust_type;
    let arms = structure
        .variants
        .iter()
        .map(|v| format!("        crate::{mod_path}::{ty}::{v} {{ .. }} => (),"))
        .collect::<Vec<_>>()
        .join("\n");
    generated.push_str(&format!(
        "/// Contract {urn}.\n\
         ///\n\
         /// Exhaustive match: a variant added to `{ty}` without amending the\n\
         /// contract fails to compile here.\n\
         #[allow(dead_code, clippy::unneeded_struct_pattern)]\n\
         fn _contract_variants_{fn_stem}(value: &crate::{mod_path}::{ty}) {{\n    \
         match value {{\n{arms}\n    }}\n}}\n\n",
    ));
}

fn render_contract_entry(
    path: &Path,
    crate_name: &str,
    module_prefix: &str,
    by_urn: &mut BTreeMap<String, String>,
    by_type: &mut BTreeMap<String, String>,
    generated: &mut String,
    generated_tests: &mut String,
) -> usize {
    let contract = load_contract_file(path);
    let Some(structure) = contract.structure else {
        return 0;
    };
    if structure.language != "rust" || structure.rust_crate != crate_name {
        return 0;
    }

    register_unique_contract(
        path,
        &contract.contract_id,
        &structure.rust_type,
        by_urn,
        by_type,
    );

    let (mod_path, fn_stem) =
        resolve_module_and_stem(module_prefix, &structure.rust_module, &structure.rust_type);

    match structure.form.as_str() {
        "struct" => {
            render_struct_contract(
                path,
                &contract.contract_id,
                &structure,
                &mod_path,
                &fn_stem,
                generated,
                generated_tests,
            );
            1
        }
        "enum" => {
            render_enum_contract(
                path,
                &contract.contract_id,
                &structure,
                &mod_path,
                &fn_stem,
                generated,
            );
            1
        }
        other => fail(&format!(
            "{} declares unknown form {other:?}; expected struct or enum",
            path.display()
        )),
    }
}

fn render_packet_contracts(crate_name: &str, module_prefix: &str) -> RenderedContracts {
    println!("cargo::rerun-if-changed=build.rs");
    println!("cargo::rerun-if-changed=../contract_shapes_build.rs");

    let dir = match contracts_dir() {
        Some(dir) => dir,
        None => fail(
            "governance packet contracts not found: expected \
             governance/contracts/contracts_pfp \
             in an ancestor of this crate. Enforcing nothing is worse than not \
             having the mechanism, so this is a build error rather than a skip.",
        ),
    };
    println!("cargo::rerun-if-changed={}", dir.display());

    let entries = discover_contract_files(&dir);

    // Reject two contracts claiming the same Rust type or the same URN before
    // generating anything: a duplicate makes the enforced shape ambiguous.
    let mut by_type: BTreeMap<String, String> = BTreeMap::new();
    let mut by_urn: BTreeMap<String, String> = BTreeMap::new();
    // Shape checks compile in EVERY build, not only under cfg(test). A contract
    // enforced only by `cargo test` is not a compile-time contract: a shape can
    // drift through any build that does not run tests.
    let mut generated = String::new();
    let mut generated_tests = String::new();
    let mut enforced = 0usize;

    for path in &entries {
        enforced += render_contract_entry(
            path,
            crate_name,
            module_prefix,
            &mut by_urn,
            &mut by_type,
            &mut generated,
            &mut generated_tests,
        );
    }

    if enforced == 0 {
        fail(&format!(
            "read {} contract files in {} but none declared a structure for \
             {}; the enforcement is wired to nothing",
            entries.len(),
            dir.display(),
            crate_name,
        ));
    }

    RenderedContracts {
        shapes_body: generated,
        tests_body: generated_tests,
        enforced,
    }
}

fn write_rendered(rendered: &RenderedContracts) {
    if rendered.enforced == 0 {
        fail("packet contract enforcement wrote nothing");
    }
    let out_dir = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR"));
    let shapes = out_dir.join("contract_shape_checks.rs");
    let shapes_text = format!("{CONTRACT_HEADER}{}", rendered.shapes_body);
    if let Err(e) = fs::write(&shapes, shapes_text) {
        fail(&format!("cannot write {}: {e}", shapes.display()));
    }
    let tests = out_dir.join("contract_serde_tests.rs");
    let tests_text = format!("{CONTRACT_HEADER}{}", rendered.tests_body);
    if let Err(e) = fs::write(&tests, tests_text) {
        fail(&format!("cannot write {}: {e}", tests.display()));
    }
    println!(
        "cargo::warning=packet contracts enforced at compile time: {}",
        rendered.enforced
    );
}

