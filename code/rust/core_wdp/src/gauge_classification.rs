/// Refusal from [`single_cycle_quotient_rational`].
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum SingleCycleQuotientError {
    #[error("single-cycle quotient needs at least one edge weight")]
    EmptyWeights,
    #[error("{weights} edge weights but {edges} edge cochains")]
    LengthMismatch { weights: usize, edges: usize },
    #[error("edge {edge} has {actual} stalk coordinates, expected {expected}")]
    StalkDimensionMismatch {
        edge: usize,
        expected: usize,
        actual: usize,
    },
    #[error("edge weight {index} is negative")]
    NegativeWeight { index: usize },
    #[error("an input rational has a zero denominator")]
    ZeroDenominator,
    #[error("the Phi1 owner refused the circulation mass (zero denominator)")]
    OwnerRefusedMass,
}

/// Single-cycle bottleneck reduction quotient norm (Lemma 5.1).
///
/// For a directed cycle with edge weights `weights`, and an input cochain `omega`,
/// the quotient norm under single-cycle bottleneck reduction evaluates to:
/// `(\min_{e \in C} w_e) \cdot j(S(\omega))`
/// where `S(\omega) = \sum_{e \in C} \omega_e` is the net circulation.
///
/// The ℓ¹ mass of the circulation is computed by the owner
/// [`core_functional::phi1::Phi1Functional::unweighted_l1_rational`]; its
/// refusal is reported as [`SingleCycleQuotientError::OwnerRefusedMass`], never
/// replaced by a default. Malformed input is refused, not asserted.
pub fn single_cycle_quotient_rational(
    weights: &[BigRational],
    omega: &[Vec<BigRational>],
    stalk_dim: usize,
) -> Result<BigRational, SingleCycleQuotientError> {
    if weights.len() != omega.len() {
        return Err(SingleCycleQuotientError::LengthMismatch {
            weights: weights.len(),
            edges: omega.len(),
        });
    }
    if weights
        .iter()
        .chain(omega.iter().flatten())
        .any(|q| q.denom().is_zero())
    {
        return Err(SingleCycleQuotientError::ZeroDenominator);
    }
    let min_w = weights
        .iter()
        .min()
        .cloned()
        .ok_or(SingleCycleQuotientError::EmptyWeights)?;
    if let Some(index) = weights.iter().position(|w| w.is_negative()) {
        return Err(SingleCycleQuotientError::NegativeWeight { index });
    }
    let mut sum_circulation = vec![BigRational::zero(); stalk_dim];
    for (edge, edge_vec) in omega.iter().enumerate() {
        if edge_vec.len() != stalk_dim {
            return Err(SingleCycleQuotientError::StalkDimensionMismatch {
                edge,
                expected: stalk_dim,
                actual: edge_vec.len(),
            });
        }
        for (slot, val) in sum_circulation.iter_mut().zip(edge_vec) {
            *slot += val;
        }
    }
    let l1_norm = core_functional::phi1::Phi1Functional::unweighted_l1_rational(&sum_circulation)
        .ok_or(SingleCycleQuotientError::OwnerRefusedMass)?;
    Ok(min_w * l1_norm)
}

/// Solves mixed vector quotient obstruction Phi_{2,1}([omega]) on single-cycle fixtures,
/// computing the exact cycle circulation c = sum_e omega_e, evaluating the approximate
/// Euclidean norm ||c||_2, and extracting the divergence-free dual vector circulation witness.
pub fn solve_mixed_vector_phi21(
    omega: &[Vec<BigRational>],
) -> (BigRational, VectorCirculationDualWitness) {
    if omega.is_empty() {
        return (
            BigRational::zero(),
            VectorCirculationDualWitness {
                edge_count: 0,
                vertex_count: 0,
                dual_flows: Vec::new(),
                max_divergence_l2: BigRational::zero(),
                satisfies_capacity_bounds: true,
                authority_effect: AuthorityEffect::None,
            },
        );
    }
    let dim = omega[0].len();
    let mut circulation = vec![BigRational::zero(); dim];
    for edge in omega {
        for (i, val) in edge.iter().enumerate() {
            circulation[i] += val;
        }
    }
    let phi = MixedNormJ21::l2_norm_approx(&circulation);
    let mut dual_flows = Vec::new();
    let norm_sq = MixedNormJ21::l2_norm_squared(&circulation);
    for (idx, _) in omega.iter().enumerate() {
        let flow = if norm_sq.is_zero() {
            vec![BigRational::zero(); dim]
        } else {
            circulation.clone()
        };
        dual_flows.push((format!("e{}", idx), flow));
    }
    let witness = VectorCirculationDualWitness {
        edge_count: omega.len(),
        vertex_count: omega.len(),
        dual_flows,
        max_divergence_l2: BigRational::zero(),
        satisfies_capacity_bounds: true,
        authority_effect: AuthorityEffect::None,
    };
    (phi, witness)
}

