/// A finite transformation monoid M generated by endomorphisms T: Q^d -> Q^d.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct TransformationMonoid {
    pub dim: usize,
    pub generators: Vec<Vec<Vec<BigRational>>>, // list of d x d matrices
    pub authority_effect: AuthorityEffect,
}

impl TransformationMonoid {
    pub fn new(dim: usize, generators: Vec<Vec<Vec<BigRational>>>) -> Self {
        for gen in &generators {
            assert_eq!(gen.len(), dim);
            for row in gen {
                assert_eq!(row.len(), dim);
            }
        }
        Self {
            dim,
            generators,
            authority_effect: AuthorityEffect::None,
        }
    }

    /// Evaluates T(x) for matrix T and vector x.
    pub fn apply_matrix(t: &[Vec<BigRational>], x: &[BigRational]) -> Vec<BigRational> {
        let dim = x.len();
        let mut out = Vec::with_capacity(dim);
        for row in t {
            let dot: BigRational = row.iter().zip(x.iter()).map(|(a, b)| a * b).sum();
            out.push(dot);
        }
        out
    }

    /// Verifies observer passivity: J(T(x)) <= J(x) for all generators T in M.
    pub fn verify_passivity<F>(&self, gauge: F, test_vectors: &[Vec<BigRational>]) -> bool
    where
        F: Fn(&[BigRational]) -> BigRational,
    {
        for x in test_vectors {
            let j_x = gauge(x);
            for gen in &self.generators {
                let tx = Self::apply_matrix(gen, x);
                let j_tx = gauge(&tx);
                if j_tx > j_x {
                    return false;
                }
            }
        }
        true
    }
}

/// Convex Polyhedral Gauge J_C(x) = inf { lambda > 0 : x in lambda C }.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ConvexPolyhedralGauge {
    pub dim: usize,
    pub extreme_points: Vec<Vec<BigRational>>, // vertices of the symmetric unit ball C
    pub dual_facets: Vec<Vec<BigRational>>, // facet normals a_i such that C = {x : |a_i . x| <= 1}
    pub authority_effect: AuthorityEffect,
}

impl ConvexPolyhedralGauge {
    /// Creates a gauge from dual facet normals: J(x) = max_i |a_i . x|.
    pub fn from_facets(dim: usize, facets: Vec<Vec<BigRational>>) -> Self {
        Self {
            dim,
            extreme_points: Vec::new(),
            dual_facets: facets,
            authority_effect: AuthorityEffect::None,
        }
    }

    /// Standard l1 gauge on Q^d: J(x) = sum_i |x_i|.
    pub fn standard_l1(dim: usize) -> Self {
        // Facets are (+-1, +-1, ..., +-1)
        let total = 1 << dim;
        let mut facets = Vec::with_capacity(total);
        for code in 0..total {
            let mut f = Vec::with_capacity(dim);
            for i in 0..dim {
                let sgn = if (code >> i) & 1 == 1 {
                    BigRational::one()
                } else {
                    -BigRational::one()
                };
                f.push(sgn);
            }
            facets.push(f);
        }
        Self::from_facets(dim, facets)
    }

    /// Evaluates gauge J(x) = max_i |a_i . x|.
    pub fn evaluate(&self, x: &[BigRational]) -> BigRational {
        assert_eq!(x.len(), self.dim);
        core_functional::observer_gauge::polyhedral_gauge(&self.dual_facets, x)
            .checked_invariant_ca589891("declared gauge facet dimensions and exact coordinates")
    }

    /// Tests whether point x is in the unit ball B = {x : J(x) <= 1}.
    pub fn contains(&self, x: &[BigRational]) -> bool {
        self.evaluate(x) <= BigRational::one()
    }

    /// Verifies whether T(B) <= B by checking all extreme points v: J(T(v)) <= 1.
    pub fn is_matrix_invariant(&self, t: &[Vec<BigRational>]) -> bool {
        if self.extreme_points.is_empty() {
            return false;
        }
        for v in &self.extreme_points {
            let tv = TransformationMonoid::apply_matrix(t, v);
            if !self.contains(&tv) {
                return false;
            }
        }
        true
    }
}

