impl std::fmt::Display for ReindexWitnessError {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(formatter, "{:?}", self)
    }
}

impl std::error::Error for ReindexWitnessError {}

/// A positive-arity input permutation, accepted only when the kernel bijection check accepts it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ReindexBijection {
    arity: usize,
}

impl ReindexBijection {
    pub fn try_new(indices: Vec<usize>) -> Result<Self, ReindexWitnessError> {
        if indices.is_empty() {
            return Err(ReindexWitnessError::Arity);
        }
        let permutation = match InputPermutation::new(indices) {
            Ok(permutation) => permutation,
            Err(_) => return Err(ReindexWitnessError::NotBijective),
        };
        let inverse = permutation.inverse();
        for (external, &planar) in inverse.as_slice().iter().enumerate() {
            let restored = permutation.as_slice().get(planar).ok_or(ReindexWitnessError::NotBijective)?;
            if *restored != external {
                return Err(ReindexWitnessError::NotBijective);
            }
        }
        Ok(Self { arity: permutation.as_slice().len() })
    }

    pub fn arity(&self) -> usize { self.arity }
}

