#[cfg(test)]
mod reindex_witness_tests {
    use super::*;

    #[test]
    fn a_permutation_inverts_back_to_the_identity() {
        let witness = ReindexBijection::try_new(vec![1, 2, 0]);
        assert!(matches!(witness, Ok(ref witness) if witness.arity() == 3));
    }

    #[test]
    fn a_repeated_index_is_refused() {
        let witness = ReindexBijection::try_new(vec![0, 0, 1]);
        assert!(matches!(witness, Err(ReindexWitnessError::NotBijective)));
    }
}
