/// Assemble `H_obstr = δᵀδ + V_defect` from validated input.
pub fn obstruction_hamiltonian(input: &QObstructionInput) -> DMatrix<f64> {
    input.coboundary.transpose() * &input.coboundary + &input.defect_potential
}

/// Split `M` into its symmetric part and disclose the discarded asymmetry.
///
/// Returns `((M + Mᵀ)/2, ‖(M − Mᵀ)/2‖_∞)`. The second component is the
/// symmetrization residual the caller must judge (and log) explicitly.
pub fn symmetrize(m: &DMatrix<f64>) -> (DMatrix<f64>, f64) {
    let sym = (m + m.transpose()) * 0.5;
    let skew = (m - m.transpose()) * 0.5;
    let residual = if skew.is_empty() { 0.0 } else { skew.amax() };
    (sym, residual)
}

/// Exponentiate a skew-symmetric generator into an orthogonal gauge element.
///
/// Refuses non-square or non-finite input and any matrix that is not exactly
/// skew-symmetric (`a[(i,j)] == -a[(j,i)]`, zero diagonal). The exponential is
/// computed by deterministic scaling-and-squaring with a truncated series;
/// orthogonality of the result should be checked by the caller against its
/// own tolerance (the conformance tests do).
fn validate_skew_symmetric_generator(generator: &DMatrix<f64>) -> Result<usize, SolverError> {
    let n = generator.nrows();
    if generator.ncols() != n {
        return Err(SolverError::Infeasible);
    }
    if generator.iter().any(|x| !x.is_finite()) {
        return Err(SolverError::NonFiniteInput);
    }
    for i in 0..n {
        for j in 0..n {
            if generator[(i, j)] + generator[(j, i)] != 0.0 {
                return Err(SolverError::Infeasible);
            }
        }
    }
    Ok(n)
}

pub fn orthogonal_gauge(generator: &DMatrix<f64>) -> Result<DMatrix<f64>, SolverError> {
    let n = validate_skew_symmetric_generator(generator)?;

    // Scaling and squaring: halve until the inf-norm is at most 1/2.
    let mut scaled = generator.clone();
    let mut squarings = 0_u32;
    while !scaled.is_empty() && scaled.amax() > 0.5 {
        scaled *= 0.5;
        squarings += 1;
    }

    let mut result = DMatrix::<f64>::identity(n, n);
    let mut term = DMatrix::<f64>::identity(n, n);
    for k in 1..=32_u32 {
        term = &term * &scaled / f64::from(k);
        result += &term;
        if term.is_empty() || term.amax() < f64::EPSILON {
            break;
        }
    }
    for _ in 0..squarings {
        result = &result * &result;
    }
    Ok(result)
}

/// Apply the gauge element `G` to the input data:
/// `δ ↦ δ Gᵀ` and `V ↦ (G V Gᵀ)` symmetrized.
///
/// Since `H(δGᵀ, GVGᵀ) = G (δᵀδ + V) Gᵀ`, this is the represented action of
/// the gauge group on input data. The floating-point conjugation can leave a
/// tiny asymmetry in the potential; it is symmetrized away and the discarded
/// magnitude is returned so the caller can refuse it if it is not negligible.
pub fn gauge_transform_input(
    input: &QObstructionInput,
    gauge: &DMatrix<f64>,
) -> (QObstructionInput, f64) {
    let coboundary = &input.coboundary * gauge.transpose();
    let conjugated = gauge * &input.defect_potential * gauge.transpose();
    let (defect_potential, symmetrization_residual) = symmetrize(&conjugated);
    (
        QObstructionInput {
            coboundary,
            defect_potential,
        },
        symmetrization_residual,
    )
}

/// Relative excited-state mass after imaginary-time evolution `exp(-t H)`.
///
/// Expands `ψ` in the receipt's eigenbasis with coefficients `c_k`, evolves
/// each as `c_k · exp(-(λ_k - λ₀) t)` (the common `exp(-λ₀ t)` factor cancels,
/// which also keeps every exponent non-positive for `t ≥ 0`, so no overflow),
/// and returns `‖excited part‖₂ / |ground coefficient|`.
///
/// For `ψ = v₀ + v₁` this equals `exp(-(λ₁ - λ₀) t)` in this model. Refuses
/// non-finite or negative `t`, dimension mismatch, and states with (numerically)
/// zero ground overlap.
pub fn imaginary_time_excited_ratio(
    receipt: &QSpectralReceipt,
    psi: &[f64],
    t: f64,
) -> Result<f64, SolverError> {
    if !t.is_finite() || psi.iter().any(|x| !x.is_finite()) {
        return Err(SolverError::NonFiniteInput);
    }
    if t < 0.0 || psi.len() != receipt.dim {
        return Err(SolverError::Infeasible);
    }
    let coefficients: Vec<f64> = receipt
        .eigenvectors
        .iter()
        .map(|v| v.iter().zip(psi).map(|(a, b)| a * b).sum())
        .collect();
    let ground = coefficients[0].abs();
    if ground < 1e-300 {
        return Err(SolverError::Infeasible);
    }
    let lambda0 = receipt.ground_energy;
    let excited_sq: f64 = coefficients
        .iter()
        .zip(&receipt.eigenvalues)
        .skip(1)
        .map(|(c, lambda)| {
            let evolved = c * (-(lambda - lambda0) * t).exp();
            evolved * evolved
        })
        .sum();
    Ok(excited_sq.sqrt() / ground)
}

fn validate_input(input: &QObstructionInput) -> Result<(), SolverError> {
    let n = input.defect_potential.nrows();
    if input
        .coboundary
        .iter()
        .chain(input.defect_potential.iter())
        .any(|x| !x.is_finite())
    {
        return Err(SolverError::NonFiniteInput);
    }
    if n == 0 || input.defect_potential.ncols() != n || input.coboundary.ncols() != n {
        return Err(SolverError::Infeasible);
    }
    for i in 0..n {
        for j in (i + 1)..n {
            if input.defect_potential[(i, j)] != input.defect_potential[(j, i)] {
                return Err(SolverError::Infeasible);
            }
        }
    }
    Ok(())
}

struct JacobiOutcome {
    values: Vec<f64>,
    vectors: DMatrix<f64>,
    sweeps: usize,
}

/// Cyclic Jacobi diagonalization of a real-symmetric matrix. Deterministic:
/// fixed sweep order, no randomization, no hidden state.
fn jacobi_eigen(h: &DMatrix<f64>, max_sweeps: usize) -> JacobiOutcome {
    let n = h.nrows();
    let mut a = h.clone();
    let mut q = DMatrix::<f64>::identity(n, n);
    let frobenius = h.iter().map(|x| x * x).sum::<f64>().sqrt();
    let stop = f64::EPSILON * frobenius.max(f64::MIN_POSITIVE) * (n as f64);
    let mut sweeps = 0;

    while sweeps < max_sweeps && off_diagonal_frobenius(&a) > stop {
        for p in 0..n.saturating_sub(1) {
            for r in (p + 1)..n {
                let apr = a[(p, r)];
                if apr == 0.0 {
                    continue;
                }
                let tau = (a[(r, r)] - a[(p, p)]) / (2.0 * apr);
                let t = if tau >= 0.0 {
                    1.0 / (tau + (1.0 + tau * tau).sqrt())
                } else {
                    -1.0 / (-tau + (1.0 + tau * tau).sqrt())
                };
                let c = 1.0 / (1.0 + t * t).sqrt();
                let s = t * c;
                for k in 0..n {
                    let akp = a[(k, p)];
                    let akr = a[(k, r)];
                    a[(k, p)] = c * akp - s * akr;
                    a[(k, r)] = s * akp + c * akr;
                }
                for k in 0..n {
                    let apk = a[(p, k)];
                    let ark = a[(r, k)];
                    a[(p, k)] = c * apk - s * ark;
                    a[(r, k)] = s * apk + c * ark;
                }
                for k in 0..n {
                    let qkp = q[(k, p)];
                    let qkr = q[(k, r)];
                    q[(k, p)] = c * qkp - s * qkr;
                    q[(k, r)] = s * qkp + c * qkr;
                }
            }
        }
        sweeps += 1;
    }

    JacobiOutcome {
        values: a.diagonal().iter().copied().collect(),
        vectors: q,
        sweeps,
    }
}

fn off_diagonal_frobenius(a: &DMatrix<f64>) -> f64 {
    let n = a.nrows();
    let mut sum = 0.0;
    for i in 0..n {
        for j in 0..n {
            if i != j {
                sum += a[(i, j)] * a[(i, j)];
            }
        }
    }
    sum.sqrt()
}

fn canonical_sign(mut v: Vec<f64>) -> Vec<f64> {
    if let Some(first) = v.iter().find(|x| x.abs() > 1e-12) {
        if *first < 0.0 {
            for x in &mut v {
                *x = -*x;
            }
        }
    }
    v
}

