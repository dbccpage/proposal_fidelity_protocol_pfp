//! Finite-truncation spectral solver for the represented obstruction operator
//! `H_obstr = L0 + V_defect`, where `L0 = δᵀδ` is the ℓ²-adjoint coboundary
//! Laplacian of a declared finite cochain carrier and `V_defect` is a
//! symmetric defect potential.
//!
//! Scope fences (Epoch 19, `PKT-20260722-RES-EPOCH19`):
//!
//! - This solver operates on **finite-dimensional real-symmetric truncations**
//!   only. Continuous Hilbert cochain spaces `H_Q` are Q-held continuum
//!   objects; nothing computed here promotes a continuum claim, and no
//!   spectral receipt mints authority.
//! - `L0 = δᵀδ` carries ℓ² spectral structure (spectral conditioning /
//!   connectivity of the carrier). It is distinct from the ℓ¹ compatibility
//!   defect norm `‖δ⁰α‖₁`, and its eigendata are not `H¹` cohomology classes.
//! - The gauge model implemented is the **real orthogonal form** `O(n)`
//!   acting by conjugation, generated by exponentials of skew-symmetric
//!   matrices. Conjugation preserves the spectrum; it is a change of
//!   represented frame, not a repair of defect content.
//! - Ground-state decay under `exp(-t · H_obstr)` is an operator-theoretic
//!   statement inside this model; it asserts nothing about physical quantum
//!   mechanics.
//!
//! Diagnostics are disclosed per [`crate::compliance`]: the eigenpair
//! residual is reported, determinism holds for identical inputs, and
//! non-finite inputs are refused with a typed error.

