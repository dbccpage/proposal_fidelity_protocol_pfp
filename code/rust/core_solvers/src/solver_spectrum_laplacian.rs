/// A carrier with **non-unit declared R3 weights**: vertex weights `w0 > 0` on
/// `C⁰` and edge weights `w1 > 0` on `C¹`.
///
/// The solver operates in the standard dot product. §S.8 gives the declared,
/// assumption-carrying change of variables that maps a weighted carrier into it:
///
/// ```text
///     δ̃ := (W¹)^{1/2} δ (W⁰)^{-1/2},   Ṽ := (W⁰)^{-1/2} V_w (W⁰)^{-1/2},
/// ```
///
/// under which `L̃₀ = δ̃ᵀδ̃` is **unitarily equivalent** to the weighted Laplacian
/// (whose eigenpairs solve the generalized problem `δᵀW¹δ f = λ W⁰ f`). This is
/// an embedding, not an identification. Feeding weighted inputs to the solver
/// *without* this transform is out of conformance scope.
#[derive(Debug, Clone, PartialEq)]
pub struct WeightedCarrier {
    /// Raw coboundary `δ : C⁰ → C¹` (`m × n`).
    pub d0: DMatrix<f64>,
    /// Vertex weights `w⁰`, length `n`, all strictly positive.
    pub w0: Vec<f64>,
    /// Edge weights `w¹`, length `m`, all strictly positive.
    pub w1: Vec<f64>,
    /// Weighted defect potential `V_w` on `C⁰` (`n × n`, symmetric).
    pub defect_potential: DMatrix<f64>,
}

/// Apply the §S.8 change of variables, returning a [`QObstructionInput`] in
/// standard-dot-product coordinates. Refuses non-positive or non-finite weights
/// and dimension mismatch.
fn validate_weighted_carrier(carrier: &WeightedCarrier) -> Result<(usize, usize), SolverError> {
    let m = carrier.d0.nrows();
    let n = carrier.d0.ncols();
    let valid_dims = carrier.w0.len() == n
        && carrier.w1.len() == m
        && carrier.defect_potential.nrows() == n
        && carrier.defect_potential.ncols() == n;
    if !valid_dims {
        return Err(SolverError::Infeasible);
    }
    if carrier
        .w0
        .iter()
        .chain(carrier.w1.iter())
        .any(|w| !w.is_finite() || *w <= 0.0)
    {
        return Err(SolverError::Infeasible);
    }
    Ok((m, n))
}

pub fn weighted_to_unit_input(carrier: &WeightedCarrier) -> Result<QObstructionInput, SolverError> {
    let (m, n) = validate_weighted_carrier(carrier)?;

    // Diagonal (W⁰)^{±1/2}, (W¹)^{1/2}.
    let w0_isqrt: Vec<f64> = carrier.w0.iter().map(|w| 1.0 / w.sqrt()).collect();
    let w1_sqrt: Vec<f64> = carrier.w1.iter().map(|w| w.sqrt()).collect();

    // δ̃ = (W¹)^{1/2} δ (W⁰)^{-1/2}: scale row i by √w¹_i, column j by 1/√w⁰_j.
    let mut coboundary = carrier.d0.clone();
    for i in 0..m {
        for j in 0..n {
            coboundary[(i, j)] *= w1_sqrt[i] * w0_isqrt[j];
        }
    }

    // Ṽ = (W⁰)^{-1/2} V_w (W⁰)^{-1/2}: scale entry (i,j) by 1/√(w⁰_i w⁰_j).
    let mut defect_potential = carrier.defect_potential.clone();
    for i in 0..n {
        for j in 0..n {
            defect_potential[(i, j)] *= w0_isqrt[i] * w0_isqrt[j];
        }
    }
    let (defect_potential, _asymmetry) = symmetrize(&defect_potential);

    Ok(QObstructionInput {
        coboundary,
        defect_potential,
    })
}

/// Prop. S2(c) Rayleigh-minimum check: the ground energy is a lower bound on the
/// Rayleigh quotient at every supplied unit test vector, and the ground
/// eigenvector attains it.
///
/// Returns `(max_violation, ground_rayleigh_error)`: `max_violation` is the
/// largest amount by which any test vector's Rayleigh value falls *below* `λ₀`
/// (should be `≤ tol`, i.e. never below), and `ground_rayleigh_error` is
/// `|O(φ₀) − λ₀|`. Conformant iff both are within tolerance.
pub fn s2_rayleigh_scan(
    input: &QObstructionInput,
    receipt: &QSpectralReceipt,
    test_vectors: &[Vec<f64>],
) -> (f64, f64) {
    let h = obstruction_hamiltonian(input);
    let rayleigh = |v: &[f64]| -> f64 {
        let n = v.len();
        let col = DMatrix::from_column_slice(n, 1, v);
        let hv = &h * &col;
        let num: f64 = v.iter().zip(hv.iter()).map(|(a, b)| a * b).sum();
        let den: f64 = v.iter().map(|x| x * x).sum();
        num / den
    };
    let mut max_violation = 0.0_f64;
    for v in test_vectors {
        let below = receipt.ground_energy - rayleigh(v);
        max_violation = max_violation.max(below);
    }
    let ground_rayleigh_error = (rayleigh(&receipt.ground_state) - receipt.ground_energy).abs();
    (max_violation, ground_rayleigh_error)
}

/// Prop. S3 excited/ground ratio bound. Returns the measured ratio
/// `‖P⊥ψ(t)‖ / ‖P₀ψ(t)‖` and the bound `e^{-(λ₁-λ₀)t} · initial_ratio`.
///
/// The measured ratio must not exceed the bound; equality holds exactly when the
/// excited part of `ψ(0)` lies in the `λ₁`-eigenspace. `None` if the spectrum has
/// no gap (GAP fails) or the ground overlap is zero (SEED fails).
pub fn s3_excited_ground_ratio(
    receipt: &QSpectralReceipt,
    psi0: &[f64],
    t: f64,
) -> Option<(f64, f64)> {
    if psi0.len() != receipt.dim || !t.is_finite() || t < 0.0 {
        return None;
    }
    let lambda0 = receipt.ground_energy;
    let lambda1 = receipt
        .eigenvalues
        .iter()
        .copied()
        .find(|l| *l > lambda0 + 1e-12)?;

    // Coefficients c_i = ⟨φ_i, ψ0⟩.
    let coeffs: Vec<f64> = receipt
        .eigenvectors
        .iter()
        .map(|v| v.iter().zip(psi0).map(|(a, b)| a * b).sum())
        .collect();

    let ground_sq = |scale: &dyn Fn(f64) -> f64| -> f64 {
        coeffs
            .iter()
            .zip(&receipt.eigenvalues)
            .filter(|(_, l)| (**l - lambda0).abs() <= 1e-12)
            .map(|(c, l)| {
                let e = scale(*l) * *c;
                e * e
            })
            .sum()
    };
    let excited_sq = |scale: &dyn Fn(f64) -> f64| -> f64 {
        coeffs
            .iter()
            .zip(&receipt.eigenvalues)
            .filter(|(_, l)| (**l - lambda0).abs() > 1e-12)
            .map(|(c, l)| {
                let e = scale(*l) * *c;
                e * e
            })
            .sum()
    };

    let g0 = ground_sq(&|_| 1.0).sqrt();
    // SEED: the ground overlap must be nonzero. Orthonormal eigenvectors leave a
    // ~1e-16 residual overlap, so the threshold is numerical, not exact zero.
    if g0 < 1e-9 {
        return None;
    }
    let x0 = excited_sq(&|_| 1.0).sqrt();
    let gt = ground_sq(&|l| (-l * t).exp()).sqrt();
    let xt = excited_sq(&|l| (-l * t).exp()).sqrt();

    let measured = xt / gt;
    let bound = (-(lambda1 - lambda0) * t).exp() * (x0 / g0);
    Some((measured, bound))
}

