/// Schema tag stamped on every [`QSpectralReceipt`].
pub const Q_SPECTRAL_RECEIPT_SCHEMA: &str = "core.q-spectral-receipt.v1";

/// Gauge model actually implemented by this module.
pub const Q_GAUGE_MODEL: &str = "O(n) real orthogonal conjugation on a finite truncation";

/// Standing truncation disclosure carried by every receipt.
pub const Q_TRUNCATION_NOTE: &str = "finite-dimensional real-symmetric truncation of a Q-level \
     Hilbert cochain space; continuum-object claims remain Q-held; this receipt mints no authority";

/// Input data for the obstruction operator `H_obstr = δᵀδ + V_defect`.
///
/// `coboundary` is the represented coboundary `δ : C⁰ → C¹` (an `m × n`
/// matrix; `m = 0` is admitted and yields `L0 = 0`). `defect_potential` is an
/// `n × n` matrix required to be exactly symmetric; use [`symmetrize`] first
/// when the potential arises from a numerically conjugated matrix.
#[derive(Debug, Clone, PartialEq)]
pub struct QObstructionInput {
    /// Represented coboundary `δ` (`m × n`).
    pub coboundary: DMatrix<f64>,
    /// Symmetric defect potential `V_defect` (`n × n`).
    pub defect_potential: DMatrix<f64>,
}

/// Spectral receipt for one finite-truncation diagonalization.
///
/// All eigendata refer to the truncation only. `eigenvalues` is ascending;
/// eigenvectors are unit ℓ² columns with the first component of magnitude
/// above `1e-12` made positive (sign canonicalization for determinism).
#[derive(Debug, Clone, PartialEq, Serialize)]
pub struct QSpectralReceipt {
    /// Schema tag ([`Q_SPECTRAL_RECEIPT_SCHEMA`]).
    pub schema: String,
    /// Truncation dimension `n`.
    pub dim: usize,
    /// Eigenvalues of `H_obstr`, ascending.
    pub eigenvalues: Vec<f64>,
    /// Smallest eigenvalue `λ₀` (the represented spectral defect minimum of
    /// this truncation).
    pub ground_energy: f64,
    /// `λ₁ − λ₀` when `dim ≥ 2`.
    pub spectral_gap: Option<f64>,
    /// Unit ground eigenvector, sign-canonical.
    pub ground_state: Vec<f64>,
    /// All eigenvectors (same order as `eigenvalues`), each unit and
    /// sign-canonical; retained so imaginary-time diagnostics can be replayed.
    pub eigenvectors: Vec<Vec<f64>>,
    /// `max_k ‖H v_k − λ_k v_k‖_∞` against the assembled `H_obstr`.
    pub residual_inf_norm: f64,
    /// Cyclic Jacobi sweeps actually performed.
    pub jacobi_sweeps: usize,
    /// Gauge model disclosure ([`Q_GAUGE_MODEL`]).
    pub gauge_model: String,
    /// Truncation disclosure ([`Q_TRUNCATION_NOTE`]).
    pub truncation_note: String,
}

/// Deterministic cyclic-Jacobi eigensolver for `H_obstr = δᵀδ + V_defect`.
#[derive(Debug, Clone)]
pub struct QObstructionSolver {
    /// Residual acceptance threshold for `converged` in the diagnostics.
    pub tolerance: f64,
    /// Hard cap on cyclic Jacobi sweeps.
    pub max_sweeps: usize,
}

impl Default for QObstructionSolver {
    fn default() -> Self {
        Self {
            tolerance: 1e-10,
            max_sweeps: 64,
        }
    }
}

impl sealed::SolverSealed for QObstructionSolver {}

fn compute_max_eigenpair_residual(
    h: &DMatrix<f64>,
    eigenvalues: &[f64],
    eigenvectors: &[Vec<f64>],
) -> Result<f64, SolverError> {
    let n = h.nrows();
    let mut residual_inf_norm = 0.0_f64;
    for (lambda, vector) in eigenvalues.iter().zip(eigenvectors) {
        let v = DMatrix::from_column_slice(n, 1, vector);
        let r = h * &v - &v * *lambda;
        residual_inf_norm = residual_inf_norm.max(r.amax());
    }
    if !residual_inf_norm.is_finite() {
        return Err(SolverError::NumericalFailure(
            "non-finite eigenpair residual".into(),
        ));
    }
    Ok(residual_inf_norm)
}

impl Solver<QObstructionInput, QSpectralReceipt> for QObstructionSolver {
    fn solve(
        &self,
        input: &QObstructionInput,
    ) -> Result<SolverResult<QSpectralReceipt>, SolverError> {
        if !self.tolerance.is_finite() || self.tolerance < 0.0 {
            return Err(SolverError::NumericalFailure(
                "tolerance must be finite and nonnegative".into(),
            ));
        }
        validate_input(input)?;
        let h = obstruction_hamiltonian(input);
        if h.iter().any(|x| !x.is_finite()) {
            return Err(SolverError::NumericalFailure(
                "floating-point overflow assembling H_obstr = δᵀδ + V_defect".into(),
            ));
        }
        let n = h.nrows();

        let jacobi = jacobi_eigen(&h, self.max_sweeps);
        if jacobi
            .values
            .iter()
            .chain(jacobi.vectors.iter())
            .any(|x| !x.is_finite())
        {
            return Err(SolverError::NumericalFailure(
                "non-finite Jacobi eigendata".into(),
            ));
        }
        let mut order: Vec<usize> = (0..n).collect();
        order.sort_by(|&i, &j| jacobi.values[i].total_cmp(&jacobi.values[j]));

        let eigenvalues: Vec<f64> = order.iter().map(|&i| jacobi.values[i]).collect();
        let eigenvectors: Vec<Vec<f64>> = order
            .iter()
            .map(|&i| canonical_sign(jacobi.vectors.column(i).iter().copied().collect()))
            .collect();

        let residual_inf_norm = compute_max_eigenpair_residual(&h, &eigenvalues, &eigenvectors)?;

        let ground_energy = eigenvalues[0];
        let spectral_gap = (n >= 2).then(|| eigenvalues[1] - eigenvalues[0]);
        if spectral_gap.is_some_and(|gap| !gap.is_finite()) {
            return Err(SolverError::NumericalFailure(
                "spectral gap overflow".into(),
            ));
        }
        let ground_state = eigenvectors[0].clone();

        let certificate_payload = serde_json::to_vec(&serde_json::json!({
            "eigenvalue": ground_energy,
            "eigenvector": ground_state,
        }))
        .map_err(|error| SolverError::NumericalFailure(format!("certificate encode: {error}")))?;

        let receipt = QSpectralReceipt {
            schema: Q_SPECTRAL_RECEIPT_SCHEMA.to_string(),
            dim: n,
            eigenvalues,
            ground_energy,
            spectral_gap,
            ground_state,
            eigenvectors,
            residual_inf_norm,
            jacobi_sweeps: jacobi.sweeps,
            gauge_model: Q_GAUGE_MODEL.to_string(),
            truncation_note: Q_TRUNCATION_NOTE.to_string(),
        };

        let diagnostics = SolverDiagnostics {
            converged: residual_inf_norm <= self.tolerance,
            primal_residual: Some(residual_inf_norm),
            dual_residual: None,
            primal_dual_gap: None,
            iteration_count: Some(jacobi.sweeps),
            tolerance: Some(self.tolerance),
            certificates: vec![Certificate {
                kind: CertificateKind::Eigenpair,
                payload: certificate_payload,
            }],
        };

        Ok(SolverResult::new_with_diagnostics(receipt, diagnostics))
    }
}

