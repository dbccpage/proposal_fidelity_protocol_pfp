/// Result of the Prop. S1(b) parity-shadow check.
///
/// The mod-2 shadow sends an integer cochain to `same`/`diff` by parity; because
/// `-n ≡ n (mod 2)`, that shadow is **orientation-free** — it does not see the
/// R2 orientation the real lifts depend on. This receipt certifies both the
/// integer complex law and that orientation-independence on a concrete pair of
/// re-orientations.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ParityShadowReceipt {
    /// `δ¹δ⁰ = 0` over `ℤ` (the cochain-complex law).
    pub delta1_delta0_zero: bool,
    /// `‖δ¹δ⁰‖_∞` over `ℤ`; zero iff `delta1_delta0_zero`.
    pub max_composite_entry: i128,
    /// The mod-2 shadow of `δ⁰` is unchanged when the supplied alternative
    /// orientation `d0_reoriented` is used (rows/signs flipped).
    pub shadow_orientation_free: bool,
}

fn imatmul(a: &[Vec<i128>], b: &[Vec<i128>]) -> Vec<Vec<i128>> {
    let rows = a.len();
    let inner = b.len();
    let cols = if inner == 0 { 0 } else { b[0].len() };
    let mut out = vec![vec![0i128; cols]; rows];
    for (i, out_row) in out.iter_mut().enumerate() {
        for k in 0..inner {
            let aik = a[i][k];
            if aik == 0 {
                continue;
            }
            for (j, out_cell) in out_row.iter_mut().enumerate() {
                *out_cell += aik * b[k][j];
            }
        }
    }
    out
}

fn mod2_shadow(m: &[Vec<i128>]) -> Vec<Vec<u8>> {
    m.iter()
        .map(|row| row.iter().map(|x| (x.rem_euclid(2)) as u8).collect())
        .collect()
}

/// Prop. S1(b): check that the integer coboundary complex composes to zero and
/// that its mod-2 shadow is orientation-free.
///
/// `d0` is `δ⁰ : C⁰ → C¹` (`|E| × |V|`), `d1` is `δ¹ : C¹ → C²` (`|T| × |E|`),
/// both with a declared R2 orientation. `d0_reoriented` is the same complex
/// under a different consistent R2 orientation (some edge signs flipped); the
/// shadows of `d0` and `d0_reoriented` must coincide entrywise.
pub fn parity_shadow_check(
    d0: &[Vec<i128>],
    d1: &[Vec<i128>],
    d0_reoriented: &[Vec<i128>],
) -> ParityShadowReceipt {
    let composite = imatmul(d1, d0);
    let max_composite_entry = composite
        .iter()
        .flat_map(|row| row.iter())
        .map(|x| x.abs())
        .max()
        .unwrap_or(0);
    ParityShadowReceipt {
        delta1_delta0_zero: max_composite_entry == 0,
        max_composite_entry,
        shadow_orientation_free: mod2_shadow(d0) == mod2_shadow(d0_reoriented),
    }
}

/// Apply the imaginary-time semigroup `e^{-t H}` to `psi` using the receipt's
/// eigendecomposition. Returns the evolved vector.
///
/// Exponents are `-t λ_k`, non-positive for `t ≥ 0`, so no overflow. Refuses
/// non-finite or negative `t` and dimension mismatch.
pub fn imaginary_time_evolve(
    receipt: &QSpectralReceipt,
    psi: &[f64],
    t: f64,
) -> Result<Vec<f64>, SolverError> {
    if !t.is_finite() || psi.iter().any(|x| !x.is_finite()) {
        return Err(SolverError::NonFiniteInput);
    }
    if t < 0.0 || psi.len() != receipt.dim {
        return Err(SolverError::Infeasible);
    }
    let mut out = vec![0.0_f64; receipt.dim];
    for (vector, lambda) in receipt.eigenvectors.iter().zip(&receipt.eigenvalues) {
        let coefficient: f64 = vector.iter().zip(psi).map(|(a, b)| a * b).sum();
        let decayed = coefficient * (-lambda * t).exp();
        for (o, v) in out.iter_mut().zip(vector) {
            *o += decayed * v;
        }
    }
    Ok(out)
}

