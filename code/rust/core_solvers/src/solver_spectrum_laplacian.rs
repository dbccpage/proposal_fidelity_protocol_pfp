/// Input for the **degree-1** obstruction operator on `C¹`,
/// `H^(1)_obstr = L₁ + V_defect` with the Hodge Laplacian
///
/// ```text
///     L₁ = d₀ d₀ᵀ  +  d₁ᵀ d₁ .
/// ```
///
/// `d1 = None` is the graph truncation `C² := 0` used throughout the corpus,
/// which leaves the down-Laplacian `d₀d₀ᵀ` alone.
///
/// This closes OB-E19-8 of Epoch 19 proposal 005: before it, the solver had no
/// `C¹`-side entry point, so degree-1 conclusions had to travel through the
/// declared SVD bridge (`spec(d₀d₀ᵀ)` and `spec(d₀ᵀd₀)` agree away from zero).
/// That bridge is still true — [`degree1_shares_nonzero_spectrum`] is the test —
/// but it is no longer the only route.
#[derive(Debug, Clone, PartialEq)]
pub struct QObstructionInputDegree1 {
    /// `d₀ : C⁰ → C¹`, an `m × n` matrix.
    pub d0: DMatrix<f64>,
    /// `d₁ : C¹ → C²`, a `p × m` matrix; `None` means `C² := 0`.
    pub d1: Option<DMatrix<f64>>,
    /// Symmetric defect potential on `C¹` (`m × m`).
    pub defect_potential: DMatrix<f64>,
}

/// Assemble `L₁ = d₀d₀ᵀ + d₁ᵀd₁`.
pub fn degree1_hodge_laplacian(input: &QObstructionInputDegree1) -> DMatrix<f64> {
    let down = &input.d0 * input.d0.transpose();
    match &input.d1 {
        Some(d1) => down + d1.transpose() * d1,
        None => down,
    }
}

/// Solve the degree-1 problem and return the same [`QSpectralReceipt`] as the
/// degree-0 path.
///
/// Both `L₁` summands are Gram matrices and are therefore symmetric in exact
/// arithmetic; the assembled operator is symmetrized before solving and the
/// discarded asymmetry is refused if it exceeds `tolerance`, rather than being
/// silently absorbed. The solve itself reuses [`QObstructionSolver`] by handing
/// it the assembled operator as the potential with an empty coboundary, so the
/// determinism, residual disclosure and certificate behaviour are identical to
/// the degree-0 route.
pub fn solve_degree1(
    solver: &QObstructionSolver,
    input: &QObstructionInputDegree1,
) -> Result<SolverResult<QSpectralReceipt>, SolverError> {
    let m = input.d0.nrows();
    if input.defect_potential.nrows() != m || input.defect_potential.ncols() != m {
        return Err(SolverError::Infeasible);
    }
    if let Some(d1) = &input.d1 {
        if d1.ncols() != m {
            return Err(SolverError::Infeasible);
        }
    }
    let assembled = degree1_hodge_laplacian(input) + &input.defect_potential;
    let (operator, asymmetry) = symmetrize(&assembled);
    if !asymmetry.is_finite() || asymmetry > solver.tolerance {
        return Err(SolverError::NumericalFailure(format!(
            "degree-1 operator asymmetry {asymmetry} exceeds tolerance {}",
            solver.tolerance
        )));
    }
    solver.solve(&QObstructionInput {
        coboundary: DMatrix::zeros(0, m),
        defect_potential: operator,
    })
}

