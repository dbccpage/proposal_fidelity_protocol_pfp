#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct SourceSnapshot {
    terms: Vec<String>,
    r: Vec<String>,
    s: Vec<String>,
    filled: Vec<[usize; 3]>,
    enabled_count: usize,
}

impl SourceSnapshot {
    fn state(&self) -> Source25State {
        Source25State::try_new(GenesisOngoingPacket {
            terms: self.terms.clone(),
            r: self.r.iter().map(|s| s.parse().unwrap()).collect(),
            s: self.s.iter().map(|s| s.parse().unwrap()).collect(),
            filled: self
                .filled
                .iter()
                .map(|&[x, y, z]| MarkedTriple { x, y, z })
                .collect(),
        })
        .unwrap()
    }
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct SourceCase {
    states: Vec<SourceSnapshot>,
    events: Vec<Source25Change>,
    addition_price: [String; 2],
}

#[derive(Deserialize)]
struct SourceFixture {
    schema: String,
    cases: Vec<SourceCase>,
}

#[test]
fn original_python_source_and_native_replay_agree_on_all_fixture_states() {
    // Input is local to this crate and regenerated by the independent source driver.
    let fixture: SourceFixture =
        serde_json::from_str(include_str!("data/native_history_cost_source.json")).unwrap();
    assert_eq!(fixture.schema, "native-history-cost-source-v1");
    assert_eq!(fixture.cases.len(), 4);
    for case in fixture.cases {
        let run = Source25Run::replay(case.states[0].state(), &case.events).unwrap();
        assert_eq!(run.states().len(), 7);
        assert_eq!(run.states().len(), case.states.len());
        for (actual, expected) in run.states().iter().zip(&case.states) {
            assert_eq!(actual, &expected.state());
            assert_eq!(actual.enabled_changes().len(), expected.enabled_count);
        }
        assert_eq!(
            run.addition_price().0,
            &case.addition_price[0].parse::<BigInt>().unwrap()
        );
        assert_eq!(
            run.addition_price().1,
            &case.addition_price[1].parse::<BigInt>().unwrap()
        );
    }
}

fn excursion(relation: SourceRelation, x: usize, y: usize) -> [Source25Change; 2] {
    [
        Source25Change::AddAssertion { relation, x, y },
        Source25Change::Remove { relation, x, y },
    ]
}

#[test]
fn actual_source_loops_retain_prices_and_occurrences_in_marked_bigint_states() {
    for n in 1..=4 {
        let huge = BigInt::one() << 140usize;
        let state = Source25State::try_new(GenesisOngoingPacket {
            terms: (0..n).map(|i| format!("t{i}")).collect(),
            r: (0..n * n)
                .map(|i| {
                    if i % 2 == 0 {
                        BigInt::zero()
                    } else {
                        &huge + i
                    }
                })
                .collect(),
            s: (0..n * n).map(|i| &huge + i).collect(),
            filled: if n >= 3 {
                vec![MarkedTriple { x: 0, y: 1, z: 2 }]
            } else {
                vec![]
            },
        })
        .unwrap();
        for relation in [SourceRelation::R, SourceRelation::S] {
            for x in 0..n {
                for y in 0..n {
                    let events = excursion(relation, x, y);
                    let once = Source25Run::replay(state.clone(), &events).unwrap();
                    let mut iterated = Source25Run::replay(state.clone(), &[]).unwrap();
                    for k in 0..=8 {
                        assert_eq!(iterated.final_state(), &state);
                        assert_eq!(iterated.changes().len(), 2 * k);
                        assert_eq!(iterated.states().len(), 2 * k + 1);
                        assert_eq!(
                            iterated.addition_price(),
                            (&BigInt::zero(), &BigInt::from(k))
                        );
                        assert_eq!(
                            iterated,
                            Source25Run::replay(state.clone(), &events.repeat(k)).unwrap()
                        );
                        iterated = iterated.then(&once).unwrap();
                    }
                }
            }
        }
    }
}

#[test]
fn state_return_is_not_a_price_preserving_history_inverse() {
    // One admitted term is required; the empty native state refuses assertions.
    let events = excursion(SourceRelation::R, 0, 0);
    assert_eq!(
        Source25Run::replay(Source25State::empty(), &events),
        Err(SourceExecutionError::DisabledChange)
    );
    let admitted = Source25Run::replay(Source25State::empty(), &[Source25Change::AddTerm]).unwrap();
    let initial = admitted.final_state().clone();
    assert!(!initial.is_enabled(events[1]));
    let once = Source25Run::replay(initial.clone(), &events).unwrap();
    let added = once.states()[1].clone();
    let backward_excursion = Source25Run::replay(added.clone(), &[events[1], events[0]]).unwrap();
    assert_eq!(backward_excursion.final_state(), &added);
    assert_eq!(backward_excursion.addition_price().1, &BigInt::one());
    assert_ne!(once, Source25Run::replay(initial.clone(), &[]).unwrap());
    // Future legality is an endpoint question; accumulated price is not.
    let five = Source25Run::replay(initial.clone(), &events.repeat(5)).unwrap();
    assert_eq!(
        five.final_state().enabled_changes(),
        initial.enabled_changes()
    );
    for next in initial.enabled_changes() {
        let suffix = Source25Run::replay(initial.clone(), &[next]).unwrap();
        let extended = five.then(&suffix).unwrap();
        assert_eq!(extended.final_state(), suffix.final_state());
        assert_eq!(
            extended.addition_price().1,
            &(suffix.addition_price().1 + 5)
        );
    }
}

#[test]
fn every_finite_cyclic_report_has_an_actual_native_price_collision() {
    let seed = Source25Run::replay(Source25State::empty(), &[Source25Change::AddTerm]).unwrap();
    for modulus in 1..=16 {
        let repeated = Source25Run::replay(
            seed.final_state().clone(),
            &excursion(SourceRelation::S, 0, 0).repeat(modulus),
        )
        .unwrap();
        let cyclic = FiniteMoore::new(
            (0..modulus).collect(),
            (0..modulus).map(|i| vec![(i + 1) % modulus, i]).collect(),
            2,
        )
        .unwrap();
        let label = repeated.changes().iter().fold(0, |label, event| {
            let input = match event {
                Source25Change::AddAssertion { .. } => 0,
                Source25Change::Remove { .. } => 1,
                _ => panic!("the fixture only contains assertion excursions"),
            };
            cyclic.transitions()[label][input]
        });
        assert_eq!(label, 0);
        assert_eq!(repeated.final_state(), seed.final_state());
        assert_eq!(repeated.addition_price().1, &BigInt::from(modulus));
        // Identity and this history have the same cyclic label but prices 0,m.
        let midpoint = BigRational::new(modulus.into(), 2.into());
        assert_eq!(
            (BigRational::from_integer(modulus.into()) - &midpoint).abs(),
            midpoint
        );
    }
}

// Exhaust all unlabeled partitions, independently of the consecutive-block construction.
fn best_diameter(n: usize, budget: usize, labels: &mut Vec<usize>, used: usize) -> usize {
    if labels.len() == n {
        return (0..used)
            .map(|label| {
                let members: Vec<_> = (0..n).filter(|&i| labels[i] == label).collect();
                members.last().unwrap() - members.first().unwrap()
            })
            .max()
            .unwrap();
    }
    let mut best = usize::MAX;
    for label in 0..used + usize::from(used < budget) {
        labels.push(label);
        best = best.min(best_diameter(n, budget, labels, used.max(label + 1)));
        labels.pop();
    }
    best
}

#[test]
fn optimal_cost_reports_match_all_partitions_on_small_windows() {
    for maximum in 0..=7usize {
        for budget in 1..=maximum + 3 {
            let report = FiniteCostReport::new(maximum.into(), budget.into()).unwrap();
            let oracle = best_diameter(maximum + 1, budget, &mut vec![], 0);
            assert_eq!(
                report.optimal_error(),
                BigRational::new(oracle.into(), 2.into())
            );
            assert!(report.used_labels() <= &BigUint::from(budget));
            let mut attained = BigRational::zero();
            for cost in 0..=maximum {
                let label = report.report(&cost.into()).unwrap();
                let (lo, hi) = report.fiber(&label).unwrap();
                assert!(lo <= cost.into() && BigUint::from(cost) <= hi);
                let error =
                    (report.decode(&label).unwrap() - BigRational::from_integer(cost.into())).abs();
                attained = attained.max(error);
            }
            assert_eq!(attained, report.optimal_error());
        }
    }
}

#[test]
fn bounded_report_refuses_bad_inputs_and_does_not_claim_a_congruence() {
    assert_eq!(
        FiniteCostReport::new(0u8.into(), 0u8.into()),
        Err(CostReportError::NoLabels)
    );
    let huge = BigUint::one() << 200usize;
    let exact = FiniteCostReport::new(huge.clone(), &huge + BigUint::one()).unwrap();
    assert_eq!(exact.optimal_error(), BigRational::zero());
    assert_eq!(exact.report(&huge).unwrap(), huge);
    assert_eq!(
        exact.report(&(&huge + BigUint::one())),
        Err(CostReportError::OutsideWindow)
    );
    assert_eq!(
        exact.decode(exact.used_labels()),
        Err(CostReportError::UnknownLabel)
    );
    let report = FiniteCostReport::new(3u8.into(), 2u8.into()).unwrap();
    assert_eq!(report.report(&0u8.into()), report.report(&1u8.into()));
    assert_ne!(report.report(&1u8.into()), report.report(&2u8.into()));
    // The same admitted +1 continuation separates the initially equal reports.
    assert_eq!(report.optimal_error(), BigRational::new(1.into(), 2.into()));
}

#[test]
fn the_seed_horizon_contains_fifty_distinct_history_prices() {
    let seed = Source25Run::replay(Source25State::empty(), &[Source25Change::AddTerm]).unwrap();
    let mut prices = std::collections::BTreeSet::new();
    for k in 0..=49 {
        let suffix = Source25Run::replay(
            seed.final_state().clone(),
            &excursion(SourceRelation::R, 0, 0).repeat(k),
        )
        .unwrap();
        let whole = seed.then(&suffix).unwrap();
        assert!(whole.changes().len() <= 100);
        assert_eq!(whole.final_state(), seed.final_state());
        prices.insert(whole.addition_price().1.clone());
    }
    assert_eq!(prices.len(), 50);
    assert_eq!(
        FiniteCostReport::new(49u8.into(), 6u8.into())
            .unwrap()
            .optimal_error(),
        BigRational::from_integer(4.into())
    );
    assert_eq!(
        FiniteCostReport::new(49u8.into(), 7u8.into())
            .unwrap()
            .optimal_error(),
        BigRational::new(7.into(), 2.into())
    );
}

fn matrix(entries: [i64; 4], denominator: i64) -> BasicMatrix<BigRational> {
    BasicMatrix::from_row_major(
        2,
        2,
        entries
            .into_iter()
            .map(|n| BigRational::new(n.into(), denominator.into()))
            .collect(),
    )
    .unwrap()
}

#[test]
fn matrix_history_encodings_can_be_injective_without_faithful_linearization() {
    let identity = matrix([1, 0, 0, 1], 1);
    let shear = matrix([1, 1, 0, 1], 1);
    let mut power = identity.clone();
    for k in 0..=64 {
        assert_eq!(power, matrix([1, k, 0, 1], 1));
        power = power.mul(&shear).unwrap();
    }
    // T^2 - 2T + I = 0: nonzero free coefficients [1,-2,1] are killed.
    let twice_shear = shear.add(&shear).unwrap();
    assert_eq!(
        shear.mul(&shear).unwrap().add(&identity).unwrap(),
        twice_shear
    );
    // A rational orthogonal control also kills a nonzero polynomial, despite
    // having infinite order (proved in the note, not by this finite test).
    let rotation = matrix([3, -4, 4, 3], 5);
    let inverse = matrix([3, 4, -4, 3], 5);
    assert_eq!(rotation.mul(&inverse).unwrap(), identity);
    let scaled = matrix([18, -24, 24, 18], 25);
    assert_eq!(
        rotation.mul(&rotation).unwrap().add(&identity).unwrap(),
        scaled
    );
}

