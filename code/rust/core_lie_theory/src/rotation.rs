//! Finite rotation groups in `SO(3, K)` for `K = Q` and `K = Q(sqrt 5)`.
//!
//! Klein's list of the finite subgroups of `SO(3)`: the cyclic groups `C_m`, the dihedral
//! groups `D_m` (order `2 m`), and the tetrahedral `T` (12), octahedral `O` (24) and
//! icosahedral `I` (60) groups. They are built here by closing exact generator matrices
//! ([`rotation_group`], a deterministic breadth-first closure with a size bound), so every
//! order and every element is computed, not quoted:
//!
//! - over `Q`: [`tetrahedral_group`], [`octahedral_group`] (signed permutation matrices),
//!   [`cyclic_rotation_group`] for `m` in `1, 2, 3, 4, 6`, and [`dihedral_rotation_group`]
//!   for `m` in `2, 3, 4, 6`;
//! - over `Q(sqrt 5)`: [`icosahedral_group`], whose generators have golden-ratio entries.
//!
//! A rotation of order `k` has trace `1 + 2 cos(2 pi j / k)`, which is rational exactly when
//! `phi(k) <= 2`, that is `k` in `1, 2, 3, 4, 6`; so `I`, whose rotations of order 5 have
//! traces `(1 +- sqrt 5)/2`, has no realisation over `Q`, while `T` and `O` do. The field of
//! a group is the trace field, generated by the traces, and its conductor is computed from
//! the element orders ([`trace_field_conductor`]); it is a property of the group, not of a
//! chosen axis-aligned form.
//!
//! Also here: [`rational_axis_angle_rotation`], the rotation about a rational axis with
//! rational cosine and `sin / |axis|`, checked to be a rotation.
//!
//! AuthorityEffect: None.


