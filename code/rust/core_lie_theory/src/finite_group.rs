/// The largest group whose full Cayley table is built.
pub const MAX_TABLE_ORDER: usize = 2048;
/// The largest group for which a character table is computed.
pub const MAX_CHARACTER_TABLE_ORDER: usize = 2000;
/// The largest number of conjugacy classes handled by the character-table algorithm.
pub const MAX_CHARACTER_TABLE_CLASSES: usize = 40;

/// Refusals for finite-group constructions.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum GroupError {
    #[error("a group needs at least one element")]
    Empty,
    #[error("the group has {order} elements, more than the table limit {limit}")]
    TableTooLarge { order: usize, limit: usize },
    #[error("the table has {rows} rows for {elements} elements")]
    TableShape { rows: usize, elements: usize },
    #[error("row {row} of the table has {len} entries for {elements} elements")]
    RowShape {
        row: usize,
        len: usize,
        elements: usize,
    },
    #[error("the table entry ({left}, {right}) = {value} is not an element index")]
    EntryOutOfRange {
        left: usize,
        right: usize,
        value: usize,
    },
    #[error("elements {first} and {second} are equal")]
    Repeated { first: usize, second: usize },
    #[error("the product of elements {left} and {right} is not in the set")]
    NotClosed { left: usize, right: usize },
    #[error("the set has no two-sided identity")]
    NoIdentity,
    #[error("element {index} has no inverse in the set")]
    NoInverse { index: usize },
    #[error("the product is not associative at ({a}, {b}, {c})")]
    NotAssociative { a: usize, b: usize, c: usize },
    #[error("element index {index} is out of range for a group of order {order}")]
    IndexOutOfRange { index: usize, order: usize },
    #[error("the generated set exceeds {bound} elements")]
    BoundExceeded { bound: usize },
    #[error("invalid parameter: {0}")]
    InvalidParameter(&'static str),
    #[error("the subset is not a subgroup: {reason}")]
    NotSubgroup { reason: &'static str },
    #[error("the subgroup is not normal")]
    NotNormal,
    #[error("a function has {actual} values, the group has {expected} elements")]
    FunctionLength { expected: usize, actual: usize },
    #[error("the group has {classes} conjugacy classes and order {order}, beyond the character-table limits")]
    CharacterTableTooLarge { order: usize, classes: usize },
    #[error("the character-table computation is internally inconsistent: {0}")]
    CharacterTableInconsistent(&'static str),
    #[error(transparent)]
    Matrix(#[from] MatrixError),
}

/// A finite group with its multiplication table. Elements are addressed by index.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct FiniteGroup<E> {
    elements: Vec<E>,
    /// Row-major: `table[a * n + b]` is the index of `elements[a] * elements[b]`.
    table: Vec<usize>,
    identity: usize,
    inverses: Vec<usize>,
}

/// The class equation `|G| = |Z(G)| + sum |C_i|` over the classes outside the centre.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ClassEquation {
    pub order: usize,
    pub centre_order: usize,
    /// Sizes of the conjugacy classes with more than one element, ascending.
    pub noncentral_class_sizes: Vec<usize>,
}

impl ClassEquation {
    /// `|Z| + sum |C_i| = |G|` and every class size divides `|G|`.
    pub fn holds(&self) -> bool {
        self.centre_order + self.noncentral_class_sizes.iter().sum::<usize>() == self.order
            && self
                .noncentral_class_sizes
                .iter()
                .all(|c| self.order % c == 0)
    }
}

/// The subgroup of `ambient` generated by `generators`, as the elements in breadth-first
/// discovery order (identity first, then right multiples of earlier elements by the
/// generators in the given order).
///
/// `key` maps an element to a canonical hashable key, so that equal elements are found
/// (the map is used for lookups only; no output depends on its iteration order).
/// `mul` must be the associative operation of a group containing `identity` and the
/// generators. If the closure has more than `bound` elements the refusal
/// [`GroupError::BoundExceeded`] is returned: a finite set closed under right
/// multiplication by the generators is the generated subgroup (right multiplication by a
/// generator is injective, hence bijective on a finite set), and no partial answer is
/// returned otherwise.
pub fn generate<E, K, M, F>(
    generators: &[E],
    identity: E,
    mul: M,
    key: F,
    bound: usize,
) -> Result<Vec<E>, GroupError>
where
    E: Clone,
    K: Hash + Eq,
    M: Fn(&E, &E) -> E,
    F: Fn(&E) -> K,
{
    if bound == 0 {
        return Err(GroupError::BoundExceeded { bound });
    }
fn try_insert_candidate<E, K: std::hash::Hash + Eq>(
    candidate: E,
    k: K,
    bound: usize,
    index: &mut HashMap<K, usize>,
    elements: &mut Vec<E>,
) -> Result<(), GroupError> {
    if let std::collections::hash_map::Entry::Vacant(slot) = index.entry(k) {
        if elements.len() == bound {
            return Err(GroupError::BoundExceeded { bound });
        }
        slot.insert(elements.len());
        elements.push(candidate);
    }
    Ok(())
}

    let mut index: HashMap<K, usize> = HashMap::new();
    index.insert(key(&identity), 0);
    let mut elements = vec![identity];
    let mut cursor = 0;
    while cursor < elements.len() {
        for generator in generators {
            let candidate = mul(&elements[cursor], generator);
            let k = key(&candidate);
            try_insert_candidate(candidate, k, bound, &mut index, &mut elements)?;
        }
        cursor += 1;
    }
    Ok(elements)
}

impl<E> FiniteGroup<E> {
    /// A group from its elements and an explicit multiplication table
    /// (`table[a][b]` is the index of the product of `a` and `b`). Closure, identity,
    /// inverses and associativity are all checked.
    pub fn from_table(elements: Vec<E>, table: Vec<Vec<usize>>) -> Result<Self, GroupError> {
        let n = elements.len();
        if n == 0 {
            return Err(GroupError::Empty);
        }
        if n > MAX_TABLE_ORDER {
            return Err(GroupError::TableTooLarge {
                order: n,
                limit: MAX_TABLE_ORDER,
            });
        }
        if table.len() != n {
            return Err(GroupError::TableShape {
                rows: table.len(),
                elements: n,
            });
        }
        let mut flat = Vec::with_capacity(n * n);
        for (row, entries) in table.iter().enumerate() {
            if entries.len() != n {
                return Err(GroupError::RowShape {
                    row,
                    len: entries.len(),
                    elements: n,
                });
            }
            for (col, value) in entries.iter().enumerate() {
                if *value >= n {
                    return Err(GroupError::EntryOutOfRange {
                        left: row,
                        right: col,
                        value: *value,
                    });
                }
                flat.push(*value);
            }
        }
        let group = Self::assemble(elements, flat)?;
        group.verify_associativity()?;
        Ok(group)
    }

    /// A group from its elements and an associative operation. Closure, identity and
    /// inverses are checked; associativity is inherited from `mul`, which must be the
    /// multiplication of a group or monoid (the tests of this crate also call
    /// [`FiniteGroup::verify_associativity`] on every constructed group that is small
    /// enough to afford it).
    pub fn from_operation<K, M, F>(elements: Vec<E>, mul: M, key: F) -> Result<Self, GroupError>
    where
        K: Hash + Eq,
        M: Fn(&E, &E) -> E,
        F: Fn(&E) -> K,
    {
        let n = elements.len();
        if n == 0 {
            return Err(GroupError::Empty);
        }
        if n > MAX_TABLE_ORDER {
            return Err(GroupError::TableTooLarge {
                order: n,
                limit: MAX_TABLE_ORDER,
            });
        }
        let mut index: HashMap<K, usize> = HashMap::new();
        for (position, element) in elements.iter().enumerate() {
            if let Some(first) = index.insert(key(element), position) {
                return Err(GroupError::Repeated {
                    first,
                    second: position,
                });
            }
        }
        let mut flat = Vec::with_capacity(n * n);
        for left in 0..n {
            for right in 0..n {
                let product = mul(&elements[left], &elements[right]);
                let slot = index
                    .get(&key(&product))
                    .ok_or(GroupError::NotClosed { left, right })?;
                flat.push(*slot);
            }
        }
        Self::assemble(elements, flat)
    }

    /// The subgroup generated by `generators`, with its table (see [`generate`]).
    pub fn generated<K, M, F>(
        generators: &[E],
        identity: E,
        mul: M,
        key: F,
        bound: usize,
    ) -> Result<Self, GroupError>
    where
        E: Clone,
        K: Hash + Eq,
        M: Fn(&E, &E) -> E,
        F: Fn(&E) -> K,
    {
        let elements = generate(generators, identity, &mul, &key, bound)?;
        Self::from_operation(elements, mul, key)
    }

    /// Identity and inverses from a full table; rejects a table that has no identity or
    /// whose rows and columns are not permutations.
    fn assemble(elements: Vec<E>, table: Vec<usize>) -> Result<Self, GroupError> {
        let n = elements.len();
        let at = |a: usize, b: usize| table[a * n + b];
        let identity = (0..n)
            .find(|&e| (0..n).all(|x| at(e, x) == x && at(x, e) == x))
            .ok_or(GroupError::NoIdentity)?;
        let mut inverses = vec![usize::MAX; n];
        for (a, slot) in inverses.iter_mut().enumerate() {
            let found = (0..n).find(|&b| at(a, b) == identity && at(b, a) == identity);
            *slot = found.ok_or(GroupError::NoInverse { index: a })?;
        }
        Ok(Self {
            elements,
            table,
            identity,
            inverses,
        })
    }

    fn check_associativity_for_pair(&self, a: usize, b: usize, n: usize) -> Result<(), GroupError> {
        let ab = self.at(a, b);
        for c in 0..n {
            if self.at(ab, c) != self.at(a, self.at(b, c)) {
                return Err(GroupError::NotAssociative { a, b, c });
            }
        }
        Ok(())
    }

    /// Check `(ab)c = a(bc)` for every triple. Cubic in the order.
    pub fn verify_associativity(&self) -> Result<(), GroupError> {
        let n = self.order();
        for a in 0..n {
            for b in 0..n {
                self.check_associativity_for_pair(a, b, n)?;
            }
        }
        Ok(())
    }

    pub fn order(&self) -> usize {
        self.elements.len()
    }

    pub fn elements(&self) -> &[E] {
        &self.elements
    }

    pub fn identity(&self) -> usize {
        self.identity
    }

    /// `table[a][b]` for indices already known to be in range.
    fn at(&self, a: usize, b: usize) -> usize {
        self.table[a * self.order() + b]
    }

    fn check(&self, index: usize) -> Result<(), GroupError> {
        if index >= self.order() {
            return Err(GroupError::IndexOutOfRange {
                index,
                order: self.order(),
            });
        }
        Ok(())
    }

    pub fn element(&self, index: usize) -> Result<&E, GroupError> {
        self.check(index)?;
        Ok(&self.elements[index])
    }

    /// The index of `elements[a] * elements[b]`.
    pub fn multiply(&self, a: usize, b: usize) -> Result<usize, GroupError> {
        self.check(a)?;
        self.check(b)?;
        Ok(self.at(a, b))
    }

    pub fn inverse(&self, a: usize) -> Result<usize, GroupError> {
        self.check(a)?;
        Ok(self.inverses[a])
    }

    /// `a^k`, by repeated squaring.
    pub fn power(&self, a: usize, mut k: u64) -> Result<usize, GroupError> {
        self.check(a)?;
        let mut base = a;
        let mut result = self.identity;
        while k > 0 {
            if k & 1 == 1 {
                result = self.at(result, base);
            }
            base = self.at(base, base);
            k >>= 1;
        }
        Ok(result)
    }

    /// The least `k >= 1` with `a^k = e`.
    pub fn element_order(&self, a: usize) -> Result<usize, GroupError> {
        self.check(a)?;
        let mut current = a;
        let mut k = 1;
        while current != self.identity {
            current = self.at(current, a);
            k += 1;
        }
        Ok(k)
    }

    /// How many elements have each order.
    pub fn order_census(&self) -> BTreeMap<usize, usize> {
        let mut census = BTreeMap::new();
        for a in 0..self.order() {
            let order = self.element_order(a).checked_invariant_66329ded("every index is in range");
            *census.entry(order).or_insert(0) += 1;
        }
        census
    }

    /// The exponent: the least common multiple of the element orders.
    pub fn exponent(&self) -> usize {
        self.order_census().keys().fold(1, |acc, &o| {
            checked_lcm_usize(acc, o).checked_invariant_66329ded(
                "the lcm of element orders of a group of order at most the table limit fits usize",
            )
        })
    }

    pub fn is_abelian(&self) -> bool {
        let n = self.order();
        (0..n).all(|a| (0..n).all(|b| self.at(a, b) == self.at(b, a)))
    }

    /// The conjugacy classes, each sorted, ordered by smallest element.
    pub fn conjugacy_classes(&self) -> Vec<Vec<usize>> {
        let n = self.order();
        let mut assigned = vec![false; n];
        let mut classes = Vec::new();
        for a in 0..n {
            if assigned[a] {
                continue;
            }
            let class: BTreeSet<usize> = (0..n)
                .map(|g| self.at(self.at(g, a), self.inverses[g]))
                .collect();
            for &member in &class {
                assigned[member] = true;
            }
            classes.push(class.into_iter().collect());
        }
        classes
    }

    /// The centralizer of `a`, sorted.
    pub fn centralizer(&self, a: usize) -> Result<Vec<usize>, GroupError> {
        self.check(a)?;
        Ok((0..self.order())
            .filter(|&g| self.at(g, a) == self.at(a, g))
            .collect())
    }

    /// The centre, sorted.
    pub fn centre(&self) -> Vec<usize> {
        let n = self.order();
        (0..n)
            .filter(|&a| (0..n).all(|g| self.at(g, a) == self.at(a, g)))
            .collect()
    }

    pub fn class_equation(&self) -> ClassEquation {
        let mut noncentral: Vec<usize> = self
            .conjugacy_classes()
            .iter()
            .map(Vec::len)
            .filter(|&size| size > 1)
            .collect();
        noncentral.sort_unstable();
        ClassEquation {
            order: self.order(),
            centre_order: self.centre().len(),
            noncentral_class_sizes: noncentral,
        }
    }

    /// The subgroup generated by `generators`, sorted.
    pub fn subgroup_generated_by(&self, generators: &[usize]) -> Result<Vec<usize>, GroupError> {
        for &g in generators {
            self.check(g)?;
        }
        let mut members = BTreeSet::new();
        members.insert(self.identity);
        let mut frontier = vec![self.identity];
        while let Some(x) = frontier.pop() {
            for &g in generators {
                let y = self.at(x, g);
                if members.insert(y) {
                    frontier.push(y);
                }
            }
        }
        Ok(members.into_iter().collect())
    }

    /// Whether `subset` is closed under the product and inverses and contains `e`.
    pub fn is_subgroup(&self, subset: &[usize]) -> Result<bool, GroupError> {
        for &g in subset {
            self.check(g)?;
        }
        let set: BTreeSet<usize> = subset.iter().copied().collect();
        Ok(set.contains(&self.identity)
            && set.iter().all(|&a| {
                set.contains(&self.inverses[a]) && set.iter().all(|&b| set.contains(&self.at(a, b)))
            }))
    }

    /// Whether the subgroup `subset` is normal in the group.
    pub fn is_normal_subgroup(&self, subset: &[usize]) -> Result<bool, GroupError> {
        if !self.is_subgroup(subset)? {
            return Ok(false);
        }
        let set: BTreeSet<usize> = subset.iter().copied().collect();
        Ok((0..self.order()).all(|g| {
            set.iter()
                .all(|&h| set.contains(&self.at(self.at(g, h), self.inverses[g])))
        }))
    }

    /// The commutator subgroup `[G, G]`, sorted.
    pub fn commutator_subgroup(&self) -> Vec<usize> {
        let n = self.order();
        let mut commutators = BTreeSet::new();
        for a in 0..n {
            for b in 0..n {
                let c = self.at(self.at(a, b), self.at(self.inverses[a], self.inverses[b]));
                commutators.insert(c);
            }
        }
        let generators: Vec<usize> = commutators.into_iter().collect();
        self.subgroup_generated_by(&generators)
            .checked_invariant_66329ded("commutators are elements of the group")
    }

    /// `|G / [G, G]|`, the order of the abelianisation.
    pub fn abelianisation_order(&self) -> usize {
        self.order() / self.commutator_subgroup().len()
    }

    /// The number of ordered pairs `(a, b)` with `ab = ba`.
    pub fn commuting_pairs(&self) -> usize {
        let n = self.order();
        (0..n)
            .map(|a| (0..n).filter(|&b| self.at(a, b) == self.at(b, a)).count())
            .sum()
    }

    /// `k(G) / |G|`, the probability that two random elements commute.
    pub fn commuting_probability(&self) -> BigRational {
        BigRational::new(
            BigInt::from(self.conjugacy_classes().len()),
            BigInt::from(self.order()),
        )
    }

    /// The quotient by a normal subgroup; an element is the sorted coset it names.
    pub fn quotient(&self, normal: &[usize]) -> Result<FiniteGroup<Vec<usize>>, GroupError> {
        if !self.is_subgroup(normal)? {
            return Err(GroupError::NotSubgroup {
                reason: "not closed under products and inverses, or missing the identity",
            });
        }
        if !self.is_normal_subgroup(normal)? {
            return Err(GroupError::NotNormal);
        }
        let n = self.order();
        let mut assigned = vec![usize::MAX; n];
        let mut cosets: Vec<Vec<usize>> = Vec::new();
        for a in 0..n {
            if assigned[a] != usize::MAX {
                continue;
            }
            let coset: BTreeSet<usize> = normal.iter().map(|&h| self.at(a, h)).collect();
            for &member in &coset {
                assigned[member] = cosets.len();
            }
            cosets.push(coset.into_iter().collect());
        }
        let m = cosets.len();
        let mut table = vec![vec![0usize; m]; m];
        for (i, left) in cosets.iter().enumerate() {
            for (j, right) in cosets.iter().enumerate() {
                table[i][j] = assigned[self.at(left[0], right[0])];
            }
        }
        FiniteGroup::from_table(cosets, table)
    }

    /// The left regular representation matrix of `a`: the permutation matrix of
    /// `x -> a x` on the basis of group elements (column `x` has its `1` in row `a x`).
    pub fn regular_representation(&self, a: usize) -> Result<BasicMatrix<BigRational>, GroupError> {
        self.check(a)?;
        let n = self.order();
        let mut m = BasicMatrix::zero(n, n)?;
        for x in 0..n {
            m.set(self.at(a, x), x, BigRational::one())?;
        }
        Ok(m)
    }

    fn check_function(&self, phi: &[BigRational]) -> Result<(), GroupError> {
        if phi.len() != self.order() {
            return Err(GroupError::FunctionLength {
                expected: self.order(),
                actual: phi.len(),
            });
        }
        Ok(())
    }

    /// The flux operator: right translation `(T_g f)(x) = f(x g)` on functions `G -> Q`.
    /// Row `x` has its single `1` in column `x g`.
    pub fn flux_operator(&self, g: usize) -> Result<BasicMatrix<BigRational>, GroupError> {
        self.check(g)?;
        let n = self.order();
        let mut t = BasicMatrix::zero(n, n)?;
        for x in 0..n {
            t.set(x, self.at(x, g), BigRational::one())?;
        }
        Ok(t)
    }

    /// The holonomy operator: multiplication by the function `phi`, the diagonal matrix of
    /// its values.
    pub fn holonomy_operator(
        &self,
        phi: &[BigRational],
    ) -> Result<BasicMatrix<BigRational>, GroupError> {
        self.check_function(phi)?;
        let n = self.order();
        let mut m = BasicMatrix::zero(n, n)?;
        for (x, value) in phi.iter().enumerate() {
            m.set(x, x, value.clone())?;
        }
        Ok(m)
    }

    /// `T_g M_phi - M_phi T_g`.
    pub fn flux_holonomy_commutator(
        &self,
        g: usize,
        phi: &[BigRational],
    ) -> Result<BasicMatrix<BigRational>, GroupError> {
        let t = self.flux_operator(g)?;
        let m = self.holonomy_operator(phi)?;
        Ok(t.mul(&m)?.sub(&m.mul(&t)?)?)
    }

    /// The operator `f -> (x -> (phi(x g) - phi(x)) f(x g))`; it equals the commutator
    /// `[T_g, M_phi]`, which vanishes exactly when `phi` is constant on the cosets `x <g>`.
    pub fn translated_difference(
        &self,
        g: usize,
        phi: &[BigRational],
    ) -> Result<BasicMatrix<BigRational>, GroupError> {
        self.check(g)?;
        self.check_function(phi)?;
        let n = self.order();
        let mut d = BasicMatrix::zero(n, n)?;
        for x in 0..n {
            let xg = self.at(x, g);
            d.set(x, xg, &phi[xg] - &phi[x])?;
        }
        Ok(d)
    }
}

