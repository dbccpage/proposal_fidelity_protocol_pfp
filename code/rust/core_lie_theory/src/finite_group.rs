/// One irreducible character: its degree and its value on each conjugacy class.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct IrreducibleCharacter {
    pub degree: usize,
    /// One value per conjugacy class, in the class order of the table.
    pub values: Vec<CyclotomicInteger>,
}

/// The character table of a finite group over `Z[zeta_e]`, `e` the exponent of the group.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CharacterTable {
    order: usize,
    exponent: usize,
    classes: Vec<Vec<usize>>,
    characters: Vec<IrreducibleCharacter>,
}

impl CharacterTable {
    pub fn group_order(&self) -> usize {
        self.order
    }

    /// The conductor `e` of the value ring `Z[zeta_e]`.
    pub fn exponent(&self) -> usize {
        self.exponent
    }

    /// The conjugacy classes, as in [`FiniteGroup::conjugacy_classes`].
    pub fn classes(&self) -> &[Vec<usize>] {
        &self.classes
    }

    /// The irreducible characters: the trivial character first, then by degree and value.
    pub fn characters(&self) -> &[IrreducibleCharacter] {
        &self.characters
    }

    pub fn degrees(&self) -> Vec<usize> {
        self.characters.iter().map(|c| c.degree).collect()
    }

    fn class_weight(&self, class: usize) -> BigInt {
        BigInt::from(self.classes[class].len())
    }

    /// `n` in the value ring. The exponent was checked against the conductor limit when
    /// the table was built, so the ring exists.
    fn integer(&self, n: BigInt) -> CyclotomicInteger {
        CyclotomicInteger::from_integer(self.exponent, n)
            .checked_invariant_66329ded("the exponent was checked against the conductor limit when the table was built")
    }

    /// `sum_j |C_j| chi_a(g_j) conj(chi_b(g_j))`, which is `|G|` if `a = b` and `0` otherwise.
    pub fn row_inner_product(&self, a: usize, b: usize) -> Option<CyclotomicInteger> {
        let (ca, cb) = (self.characters.get(a)?, self.characters.get(b)?);
        let mut acc = self.integer(BigInt::zero());
        for j in 0..self.classes.len() {
            let term = ca.values[j]
                .mul(&cb.values[j].conjugate())
                .ok()?
                .scale(&self.class_weight(j));
            acc = acc.add(&term).ok()?;
        }
        Some(acc)
    }

    /// `(1/|G|) sum_j |C_j| f(g_j) conj(chi_i(g_j))`, the multiplicity of the irreducible
    /// character `i` in the class function `f` (one value per class). `None` if `f` has the
    /// wrong number of values or conductor, if `i` is out of range, or if the multiplicity is
    /// not an integer, which means `f` is not a character.
    pub fn multiplicity(&self, class_function: &[CyclotomicInteger], i: usize) -> Option<BigInt> {
        let chi = self.characters.get(i)?;
        if class_function.len() != self.classes.len() {
            return None;
        }
        let mut acc = self.integer(BigInt::zero());
        for (j, value) in class_function.iter().enumerate() {
            let term = value
                .mul(&chi.values[j].conjugate())
                .ok()?
                .scale(&self.class_weight(j));
            acc = acc.add(&term).ok()?;
        }
        let total = acc.as_integer()?;
        let order = BigInt::from(self.order);
        if &total % &order != BigInt::zero() {
            return None;
        }
        Some(total / order)
    }

    /// The McKay matrix of a character `f`: entry `[i][j]` is the multiplicity of the
    /// irreducible `j` in `f chi_i`. For a faithful 2-dimensional character of a binary
    /// polyhedral group this is the adjacency matrix of an extended Dynkin diagram.
    pub fn mckay_matrix(&self, f: &[CyclotomicInteger]) -> Option<Vec<Vec<usize>>> {
        let k = self.characters.len();
        let mut matrix = vec![vec![0usize; k]; k];
        for (i, chi_i) in self.characters.iter().enumerate() {
            let product: Option<Vec<CyclotomicInteger>> = f
                .iter()
                .zip(&chi_i.values)
                .map(|(a, b)| a.mul(b).ok())
                .collect();
            let product = product?;
            for (j, slot) in matrix[i].iter_mut().enumerate() {
                *slot = usize::try_from(self.multiplicity(&product, j)?).ok()?;
            }
        }
        Some(matrix)
    }

    /// The row orthogonality relations, exactly.
    pub fn verify_row_orthogonality(&self) -> bool {
        let n = self.characters.len();
        let order = self.integer(BigInt::from(self.order));
        (0..n).all(|a| {
            (0..n).all(|b| {
                self.row_inner_product(a, b).is_some_and(|ip| {
                    if a == b {
                        ip == order
                    } else {
                        ip.is_zero()
                    }
                })
            })
        })
    }

    /// The column orthogonality relations `sum_chi chi(g_i) conj(chi(g_j)) = |C_G(g_i)| delta_ij`.
    pub fn verify_column_orthogonality(&self) -> bool {
        let k = self.classes.len();
        (0..k).all(|i| {
            (0..k).all(|j| {
                let mut acc = self.integer(BigInt::zero());
                for c in &self.characters {
                    let Ok(term) = c.values[i].mul(&c.values[j].conjugate()) else {
                        return false;
                    };
                    let Ok(next) = acc.add(&term) else {
                        return false;
                    };
                    acc = next;
                }
                let expected = if i == j {
                    self.integer(BigInt::from(self.order / self.classes[i].len()))
                } else {
                    self.integer(BigInt::zero())
                };
                acc == expected
            })
        })
    }

    /// `sum_chi chi(1)^2 = |G|`.
    pub fn degrees_square_sum_to_order(&self) -> bool {
        self.characters
            .iter()
            .map(|c| c.degree * c.degree)
            .sum::<usize>()
            == self.order
    }

    /// The regular character `sum_chi chi(1) chi(g) = |G| delta_{g, e}` on every class.
    pub fn verify_regular_character(&self, identity_class: usize) -> bool {
        (0..self.classes.len()).all(|j| {
            let mut acc = self.integer(BigInt::zero());
            for c in &self.characters {
                let term = c.values[j].scale(&BigInt::from(c.degree));
                let Ok(next) = acc.add(&term) else {
                    return false;
                };
                acc = next;
            }
            let expected = if j == identity_class {
                self.integer(BigInt::from(self.order))
            } else {
                self.integer(BigInt::zero())
            };
            acc == expected
        })
    }
}

fn mod_pow(mut base: u64, mut exp: u64, p: u64) -> u64 {
    let mut acc = 1 % p;
    base %= p;
    while exp > 0 {
        if exp & 1 == 1 {
            acc = acc * base % p;
        }
        base = base * base % p;
        exp >>= 1;
    }
    acc
}

fn mod_inv(a: u64, p: u64) -> Option<u64> {
    if a % p == 0 {
        None
    } else {
        Some(mod_pow(a, p - 2, p))
    }
}

fn is_prime(n: u64) -> bool {
    n >= 2 && (2..).take_while(|d| d * d <= n).all(|d| n % d != 0)
}

fn prime_factors(mut n: u64) -> Vec<u64> {
    let mut out = Vec::new();
    let mut d = 2;
    while d * d <= n {
        if n % d == 0 {
            out.push(d);
            while n % d == 0 {
                n /= d;
            }
        }
        d += 1;
    }
    if n > 1 {
        out.push(n);
    }
    out
}

fn primitive_root(p: u64) -> u64 {
    let factors = prime_factors(p - 1);
    (2..p)
        .find(|&g| factors.iter().all(|&q| mod_pow(g, (p - 1) / q, p) != 1))
        .unwrap_or(1)
}

fn eliminate_rows_mod_p(
    m: &mut [Vec<u64>],
    rows: usize,
    cols: usize,
    pivot_row: usize,
    col: usize,
    p: u64,
) {
    for r in 0..rows {
        if r != pivot_row && m[r][col] != 0 {
            let factor = m[r][col];
            for c in 0..cols {
                let sub = factor * m[pivot_row][c] % p;
                m[r][c] = (m[r][c] + p - sub) % p;
            }
        }
    }
}

/// A basis of `{c : A c = 0}` for `A` with `rows` rows over `F_p`, each row of length `cols`.
fn nullspace_mod_p(a: &[Vec<u64>], cols: usize, p: u64) -> Vec<Vec<u64>> {
    let mut m: Vec<Vec<u64>> = a.to_vec();
    let rows = m.len();
    let mut pivot_columns = Vec::new();
    let mut pivot_row = 0;
    for col in 0..cols {
        if pivot_row == rows {
            break;
        }
        let Some(found) = (pivot_row..rows).find(|&r| m[r][col] != 0) else {
            continue;
        };
        m.swap(pivot_row, found);
        let inv = mod_inv(m[pivot_row][col], p).checked_invariant_66329ded("a nonzero pivot is invertible mod a prime");
        for c in 0..cols {
            m[pivot_row][c] = m[pivot_row][c] * inv % p;
        }
        eliminate_rows_mod_p(&mut m, rows, cols, pivot_row, col, p);
        pivot_columns.push(col);
        pivot_row += 1;
    }
    let is_pivot: Vec<bool> = (0..cols).map(|c| pivot_columns.contains(&c)).collect();
    let mut basis = Vec::new();
    for free in (0..cols).filter(|c| !is_pivot[*c]) {
        let mut v = vec![0u64; cols];
        v[free] = 1;
        for (row, &pc) in pivot_columns.iter().enumerate() {
            v[pc] = (p - m[row][free]) % p;
        }
        basis.push(v);
    }
    basis
}

/// Split the space spanned by `basis` into the eigenspaces of `matrix` (all eigenvalues in `F_p`).
fn split_by_eigenvalues(
    matrix: &[Vec<u64>],
    basis: &[Vec<u64>],
    k: usize,
    p: u64,
) -> Option<Vec<Vec<Vec<u64>>>> {
    let d = basis.len();
    // Columns M v_b.
    let images: Vec<Vec<u64>> = basis
        .iter()
        .map(|v| {
            (0..k)
                .map(|r| (0..k).fold(0u64, |acc, c| (acc + matrix[r][c] * v[c]) % p))
                .collect()
        })
        .collect();
    let mut parts = Vec::new();
    let mut total = 0;
    for lambda in 0..p {
        // Rows of the (k x d) system (M - lambda) sum_b c_b v_b = 0.
        let system: Vec<Vec<u64>> = (0..k)
            .map(|r| {
                (0..d)
                    .map(|b| (images[b][r] + p - lambda * basis[b][r] % p) % p)
                    .collect()
            })
            .collect();
        let kernel = nullspace_mod_p(&system, d, p);
        if kernel.is_empty() {
            continue;
        }
        total += kernel.len();
        let vectors: Vec<Vec<u64>> = kernel
            .iter()
            .map(|c| {
                (0..k)
                    .map(|r| (0..d).fold(0u64, |acc, b| (acc + c[b] * basis[b][r]) % p))
                    .collect()
            })
            .collect();
        parts.push(vectors);
        if total == d {
            break;
        }
    }
    (total == d).then_some(parts)
}

fn validate_character_table_limits(n: usize, k: usize, exponent: usize) -> Result<(), GroupError> {
    if n > MAX_CHARACTER_TABLE_ORDER
        || k > MAX_CHARACTER_TABLE_CLASSES
        || exponent > MAX_CONDUCTOR
    {
        return Err(GroupError::CharacterTableTooLarge {
            order: n,
            classes: k,
        });
    }
    Ok(())
}

fn compute_class_intersection_tensor<E>(
    group: &FiniteGroup<E>,
    classes: &[Vec<usize>],
    reps: &[usize],
    class_of: &[usize],
    k: usize,
) -> Vec<Vec<Vec<u64>>> {
    let mut a = vec![vec![vec![0u64; k]; k]; k];
    for (l, &z) in reps.iter().enumerate() {
        for (i, class) in classes.iter().enumerate() {
            for &x in class {
                let y = group.at(group.inverses[x], z);
                a[i][class_of[y]][l] += 1;
            }
        }
    }
    a
}

fn find_character_prime(n: usize, exponent: usize) -> Result<(u64, u64, u64), GroupError> {
    let inconsistent = GroupError::CharacterTableInconsistent;
    let mut p = 1 + exponent as u64 * ((2 * n as u64) / exponent as u64 + 1);
    while !is_prime(p) {
        p += exponent as u64;
    }
    let generator = primitive_root(p);
    let zeta = mod_pow(generator, (p - 1) / exponent as u64, p);
    let zeta_inverse =
        mod_inv(zeta, p).ok_or_else(|| inconsistent("the root of unity is a unit"))?;
    Ok((p, zeta, zeta_inverse))
}

fn compute_simultaneous_eigenspaces(
    matrices: &[Vec<Vec<u64>>],
    k: usize,
    p: u64,
) -> Result<Vec<Vec<Vec<u64>>>, GroupError> {
    let inconsistent = GroupError::CharacterTableInconsistent;
    let standard: Vec<Vec<u64>> = (0..k)
        .map(|i| (0..k).map(|j| u64::from(i == j)).collect())
        .collect();
    let mut spaces: Vec<Vec<Vec<u64>>> = vec![standard];
    for matrix in matrices {
        let mut next = Vec::new();
        for space in spaces {
            if space.len() == 1 {
                next.push(space);
                continue;
            }
            let parts = split_by_eigenvalues(matrix, &space, k, p).ok_or_else(|| {
                inconsistent("a class matrix did not split over the prime field")
            })?;
            next.extend(parts);
        }
        spaces = next;
    }
    if spaces.len() != k || spaces.iter().any(|s| s.len() != 1) {
        return Err(inconsistent(
            "the common eigenspaces are not one-dimensional",
        ));
    }
    Ok(spaces)
}

fn reconstruct_character_value<E>(
    group: &FiniteGroup<E>,
    rep: usize,
    degree: u64,
    chi: &[u64],
    class_of: &[usize],
    exponent: usize,
    p: u64,
    zeta_inverse: u64,
) -> Result<CyclotomicInteger, GroupError> {
    let inconsistent = GroupError::CharacterTableInconsistent;
    let m = group
        .element_order(rep)
        .checked_invariant_66329ded("a class representative is an element") as u64;
    let m_inverse = mod_inv(m % p, p)
        .ok_or_else(|| inconsistent("the element order vanishes mod p"))?;
    let step = exponent as u64 / m;
    let mut terms: Vec<(usize, BigInt)> = Vec::new();
    let mut total = 0u64;
    for t in 0..m {
        let mut sum = 0u64;
        for s_power in 0..m {
            let element = group
                .power(rep, s_power)
                .checked_invariant_66329ded("an element power is an element");
            let value = chi[class_of[element]];
            sum = (sum
                + value
                    * mod_pow(zeta_inverse, step * t * s_power % exponent as u64, p))
                % p;
        }
        let multiplicity = sum * m_inverse % p;
        if multiplicity > degree {
            return Err(inconsistent(
                "an eigenvalue multiplicity exceeds the degree",
            ));
        }
        total += multiplicity;
        if multiplicity > 0 {
            terms.push(((step * t) as usize, BigInt::from(multiplicity)));
        }
    }
    if total != degree {
        return Err(inconsistent(
            "the eigenvalue multiplicities do not sum to the degree",
        ));
    }
    CyclotomicInteger::from_formal_sum(exponent, &terms)
        .map_err(|_| inconsistent("the value ring could not be built"))
}

fn normalize_eigenspace_vector(
    space: &[Vec<u64>],
    identity_class: usize,
    p: u64,
) -> Result<Vec<u64>, GroupError> {
    let mut omega = space[0].clone();
    let scale = mod_inv(omega[identity_class], p).ok_or_else(|| {
        GroupError::CharacterTableInconsistent("a central character vanishes at the identity class")
    })?;
    for w in &mut omega {
        *w = *w * scale % p;
    }
    Ok(omega)
}

fn compute_character_degree(
    omega: &[u64],
    sizes: &[u64],
    inverse_class: &[usize],
    order_residue: u64,
    k: usize,
    p: u64,
) -> Result<u64, GroupError> {
    let inconsistent = GroupError::CharacterTableInconsistent;
    let mut s = 0u64;
    for j in 0..k {
        let size_inverse = mod_inv(sizes[j] % p, p)
            .ok_or_else(|| inconsistent("a class size vanishes mod p"))?;
        s = (s + omega[j] * omega[inverse_class[j]] % p * size_inverse) % p;
    }
    let s_inverse = mod_inv(s, p)
        .ok_or_else(|| inconsistent("the degree formula has a vanishing denominator"))?;
    let degree_squared = order_residue * s_inverse % p;
    let degree = (0..)
        .take_while(|d: &u64| d * d <= degree_squared)
        .last()
        .unwrap_or(0);
    if degree == 0 || degree * degree != degree_squared {
        return Err(inconsistent("the degree is not an integer square root"));
    }
    Ok(degree)
}

fn extract_character_from_eigenspace<E>(
    group: &FiniteGroup<E>,
    space: &[Vec<u64>],
    identity_class: usize,
    sizes: &[u64],
    inverse_class: &[usize],
    reps: &[usize],
    class_of: &[usize],
    order_residue: u64,
    k: usize,
    exponent: usize,
    p: u64,
    zeta_inverse: u64,
) -> Result<IrreducibleCharacter, GroupError> {
    let omega = normalize_eigenspace_vector(space, identity_class, p)?;
    let degree = compute_character_degree(&omega, sizes, inverse_class, order_residue, k, p)?;
    let chi: Vec<u64> = (0..k)
        .map(|j| {
            let size_inverse = mod_inv(sizes[j] % p, p).checked_invariant_66329ded("checked above");
            omega[j] * degree % p * size_inverse % p
        })
        .collect();
    let mut values = Vec::with_capacity(k);
    for &rep in reps {
        values.push(reconstruct_character_value(
            group,
            rep,
            degree,
            &chi,
            class_of,
            exponent,
            p,
            zeta_inverse,
        )?);
    }
    Ok(IrreducibleCharacter {
        degree: degree as usize,
        values,
    })
}

fn sort_and_verify_characters(
    n: usize,
    exponent: usize,
    classes: Vec<Vec<usize>>,
    mut characters: Vec<IrreducibleCharacter>,
    k: usize,
) -> Result<CharacterTable, GroupError> {
    let inconsistent = GroupError::CharacterTableInconsistent;
    let trivial: Vec<CyclotomicInteger> = (0..k)
        .map(|_| {
            CyclotomicInteger::from_integer(exponent, BigInt::one())
                .map_err(|_| inconsistent("the value ring could not be built"))
        })
        .collect::<Result<_, _>>()?;
    characters.sort_by(|x, y| {
        let x_trivial = x.values == trivial;
        let y_trivial = y.values == trivial;
        y_trivial
            .cmp(&x_trivial)
            .then(x.degree.cmp(&y.degree))
            .then_with(|| {
                let key = |c: &IrreducibleCharacter| -> Vec<Vec<BigInt>> {
                    c.values.iter().map(|v| v.coefficients().to_vec()).collect()
                };
                key(x).cmp(&key(y))
            })
    });

    let table = CharacterTable {
        order: n,
        exponent,
        classes,
        characters,
    };
    if !(table.degrees_square_sum_to_order() && table.verify_row_orthogonality()) {
        return Err(inconsistent(
            "the computed characters fail the orthogonality relations",
        ));
    }
    Ok(table)
}

impl<E> FiniteGroup<E> {
    /// The irreducible characters over `Z[zeta_e]`, `e` the exponent of the group.
    ///
    /// Dixon's algorithm: the class-sum structure constants `a_{ijl}` are reduced modulo a
    /// prime `p = 1 (mod e)` with `p > 2 |G|`, where every eigenvalue of every class matrix
    /// lies in `F_p`; the common eigenvectors are the central characters
    /// `core_chi(C_j) = |C_j| chi(g_j) / chi(1)`, from which `chi(1)` is the exact square
    /// root of `|G| / sum_j core_j omega_{j*} / |C_j|` (it is below `p`, so its residue is
    /// itself). The value `chi(g)` is `sum_t n_t zeta_m^t` with the multiplicities `n_t` of
    /// the eigenvalues of `g`, `n_t = (1/m) sum_s chi(g^s) zeta_m^(-ts)` computed modulo
    /// `p` and read back as integers in `0..=chi(1)`.
    pub fn character_table(&self) -> Result<CharacterTable, GroupError> {
        let n = self.order();
        let classes = self.conjugacy_classes();
        let k = classes.len();
        let exponent = self.exponent();
        validate_character_table_limits(n, k, exponent)?;

        let mut class_of = vec![0usize; n];
        for (j, class) in classes.iter().enumerate() {
            for &x in class {
                class_of[x] = j;
            }
        }
        let sizes: Vec<u64> = classes.iter().map(|c| c.len() as u64).collect();
        let reps: Vec<usize> = classes.iter().map(|c| c[0]).collect();
        let identity_class = class_of[self.identity];
        let inverse_class: Vec<usize> = reps.iter().map(|&r| class_of[self.inverses[r]]).collect();

        // a[i][j][l] = #{x in C_i : x^-1 z_l in C_j}, z_l the representative of class l.
        // A prime p = 1 (mod e), p > 2 |G|.
        let a = compute_class_intersection_tensor(self, &classes, &reps, &class_of, k);
        let (p, _zeta, zeta_inverse) = find_character_prime(n, exponent)?;

        // Class matrices modulo p, and their common eigenvectors.
        let matrices: Vec<Vec<Vec<u64>>> = (0..k)
            .map(|i| {
                (0..k)
                    .map(|j| (0..k).map(|l| a[i][j][l] % p).collect())
                    .collect()
            })
            .collect();
        let spaces = compute_simultaneous_eigenspaces(&matrices, k, p)?;

        let order_residue = n as u64 % p;
        let mut characters = Vec::with_capacity(k);
        for space in &spaces {
            // chi(1)^2 = |G| / sum_j core_j omega_{j*} / |C_j|.
            // chi(g_j) mod p.
            // Lift: the multiplicities of the eigenvalues of g_j.
            characters.push(extract_character_from_eigenspace(
                self,
                space,
                identity_class,
                &sizes,
                &inverse_class,
                &reps,
                &class_of,
                order_residue,
                k,
                exponent,
                p,
                zeta_inverse,
            )?);
        }

        // The trivial character first, then by degree and canonical value.
        sort_and_verify_characters(n, exponent, classes, characters, k)
    }

    /// The index of the class containing the identity in [`FiniteGroup::conjugacy_classes`].
    pub fn identity_class(&self) -> usize {
        self.conjugacy_classes()
            .iter()
            .position(|c| c.contains(&self.identity))
            .checked_invariant_66329ded("the identity lies in some class")
    }
}

impl<E: PartialEq> FiniteGroup<E> {
    /// The index of `element`, if it belongs to the group.
    pub fn index_of(&self, element: &E) -> Option<usize> {
        self.elements.iter().position(|e| e == element)
    }
}

