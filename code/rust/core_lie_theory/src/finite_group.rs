//! Finite groups by Cayley table, and the constructions every finite-group computation needs.
//!
//! A [`FiniteGroup`] is a set of labelled elements with a full multiplication table. The
//! table is checked on construction: closure, a two-sided identity, inverses (every row
//! and column is a permutation) and, for a hand-written table, associativity. A group
//! given by an associative operation (matrix product, composition of permutations) is
//! built by [`FiniteGroup::from_operation`], which checks closure, identity and inverses
//! and inherits associativity from the operation.
//!
//! - [`generate`]: the subgroup generated by some elements of an ambient group, as a
//!   deterministic breadth-first closure with a declared size bound. Exceeding the bound is
//!   the typed refusal [`GroupError::BoundExceeded`]; a generated set is returned only
//!   when it is closed, and then it is the subgroup.
//! - element orders, conjugacy classes, the class equation, the centre, the commutator
//!   subgroup, the abelianisation, normal subgroups and quotients;
//! - [`FiniteGroup::commuting_pairs`], the count of ordered commuting pairs, which equals
//!   `|G| k(G)` for `k(G)` conjugacy classes (checked in the tests, not assumed);
//! - the regular representation and the flux and holonomy operators on functions on the
//!   group (right translation and multiplication operators);
//! - [`FiniteGroup::character_table`]: the irreducible characters, computed by
//!   Burnside's class-algebra method carried out modulo a prime `p = 1 (mod e)` (Dixon),
//!   and lifted to `Z[zeta_e]` exactly: each value is a nonnegative-integer combination of
//!   `e`-th roots of unity whose multiplicities are below `p`, so the residues determine
//!   them. The orthogonality relations are then checked in `Z[zeta_e]`, not in floating
//!   point.
//!
//! The tables of permutation groups ([`symmetric_group`], [`alternating_group`],
//! [`dihedral_group`], [`cyclic_group`]) are provided so that every other construction of
//! this crate can be cross-checked against an independently built group.
//!
//! AuthorityEffect: None.


