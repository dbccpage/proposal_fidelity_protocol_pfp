fn compose(a: &[usize], b: &[usize]) -> Vec<usize> {
    // (a b)(x) = a(b(x)).
    b.iter().map(|&x| a[x]).collect()
}

fn permutation_group(
    points: usize,
    generators: &[Vec<usize>],
    bound: usize,
) -> Result<FiniteGroup<Vec<usize>>, GroupError> {
    let identity: Vec<usize> = (0..points).collect();
    FiniteGroup::generated(
        generators,
        identity,
        |a, b| compose(a, b),
        |p| p.clone(),
        bound,
    )
}

/// The symmetric group `S_n` on `0..n` as permutations `x -> image[x]`, with
/// `(a b)(x) = a(b(x))`. Refused for `n = 0` and when `n!` exceeds the table limit.
pub fn symmetric_group(n: usize) -> Result<FiniteGroup<Vec<usize>>, GroupError> {
    if n == 0 {
        return Err(GroupError::Empty);
    }
    if n == 1 {
        return permutation_group(1, &[], MAX_TABLE_ORDER);
    }
    let mut transposition: Vec<usize> = (0..n).collect();
    transposition.swap(0, 1);
    let cycle: Vec<usize> = (0..n).map(|x| (x + 1) % n).collect();
    permutation_group(n, &[transposition, cycle], MAX_TABLE_ORDER)
}

/// The alternating group `A_n`, generated by the 3-cycles `(0 1 k)`.
pub fn alternating_group(n: usize) -> Result<FiniteGroup<Vec<usize>>, GroupError> {
    if n == 0 {
        return Err(GroupError::Empty);
    }
    let generators: Vec<Vec<usize>> = (2..n)
        .map(|k| {
            let mut p: Vec<usize> = (0..n).collect();
            p[0] = 1;
            p[1] = k;
            p[k] = 0;
            p
        })
        .collect();
    permutation_group(n, &generators, MAX_TABLE_ORDER)
}

/// The dihedral group of order `2 n`, the symmetries of the regular `n`-gon for `n >= 3`,
/// as permutations of the `n` vertices.
pub fn dihedral_group(n: usize) -> Result<FiniteGroup<Vec<usize>>, GroupError> {
    if n < 3 {
        return Err(GroupError::InvalidParameter(
            "a dihedral group of a polygon needs at least 3 vertices",
        ));
    }
    let rotation: Vec<usize> = (0..n).map(|x| (x + 1) % n).collect();
    let reflection: Vec<usize> = (0..n).map(|x| (n - x) % n).collect();
    let group = permutation_group(n, &[rotation, reflection], MAX_TABLE_ORDER)?;
    Ok(group)
}

/// The cyclic group of order `n` as rotations of `n` points.
pub fn cyclic_group(n: usize) -> Result<FiniteGroup<Vec<usize>>, GroupError> {
    if n == 0 {
        return Err(GroupError::Empty);
    }
    let rotation: Vec<usize> = (0..n).map(|x| (x + 1) % n).collect();
    permutation_group(n, &[rotation], MAX_TABLE_ORDER)
}

