fn check_ki_distinct(
    previous: Option<u64>,
    current: u64,
    distinct: u16,
) -> Result<(), KiCensusError> {
    if previous == Some(current) {
        return Err(KiCensusError::new(
            "a ziggurat key is repeated",
            u128::from(current),
            u128::from(distinct),
        ));
    }
    Ok(())
}

