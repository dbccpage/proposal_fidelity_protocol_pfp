/// Integer census of the ziggurat key table: 256 distinct keys and exactly one zero.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) struct KiCensus {
    distinct: u16,
    zeros: u16,
}
pub(super) fn try_ki_census() -> Result<KiCensus, KiCensusError> {
    let mut keys = KI;
    keys.sort_unstable();
    let mut distinct = 0u16;
    let mut zeros = 0u16;
    let mut index = 0usize;
    let mut previous: Option<u64> = None;
    while index < keys.len() {
        let current = read_ki_key(&keys, index)?;
        check_ki_distinct(previous, current, distinct)?;
        previous = Some(current);
        distinct = bump_u16(distinct, "distinct count overflow")?;
        if current == 0 {
            zeros = bump_u16(zeros, "zero count overflow")?;
        }
        index = bump_ki_index(index)?;
    }
    if distinct != 256 || zeros != 1 {
        return Err(KiCensusError::new(
            "the key table does not have 256 distinct keys and one zero",
            u128::from(distinct),
            u128::from(zeros),
        ));
    }
    Ok(KiCensus { distinct, zeros })
}

