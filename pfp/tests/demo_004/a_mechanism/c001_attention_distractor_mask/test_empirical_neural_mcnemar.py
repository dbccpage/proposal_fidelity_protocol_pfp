"""
test_empirical_neural_mcnemar.py — Targeted test suite for empirical neural model inference
with eager attention hooks and McNemar statistical significance evaluation.

Verifies:
1. Exact rational McNemar test computation (Zero-Float Law).
2. Distractor span deletion logic for Arm F-delete.
3. Neural output parsing and schema normalization.
4. Physical neural inference execution on real weights (Qwen2.5-0.5B-Instruct):
   - Validity gate: Arm F-null reproduces Arm A output token IDs 100%.
   - Eager attention zeroing: distractor attention mass drops to 0.0.
   - Recording of actual output token IDs across intervention arms.
5. Strict Claim Hygiene: zero forbidden hype verbs and mandatory 4-part structure.
6. Pure UTF-8 encoding without BOM.

AuthorityEffect: None.
"""

from __future__ import annotations

import pytest

try:
    import torch
except ImportError:
    torch = None

from omega_engine_projects.mssn_sn_symgam.challenges.a_mechanism.c001_attention_distractor_mask.case_generator import (
    generate_case,
)
from omega_engine_projects.mssn_sn_symgam.challenges.a_mechanism.c001_attention_distractor_mask.empirical_neural_mcnemar_evaluation import (
    DEFAULT_LOCAL_SNAPSHOT,
    compute_mcnemar_exact,
    get_or_load_neural_model,
    parse_neural_output,
    remove_distractor_spans,
    run_empirical_neural_mcnemar_evaluation,
    run_single_neural_case,
)


class TestEmpiricalNeuralMcNemar:
    """Targeted tests for empirical neural inference and McNemar significance evaluation."""

    def test_compute_mcnemar_exact_properties(self):
        """Verifies exact rational McNemar statistic and binomial p-value computation."""
        # Zero discordant pairs
        res_zero = compute_mcnemar_exact(0, 0)
        assert res_zero["total_discordant"] == 0
        assert res_zero["chi2"] == "0"
        assert res_zero["p_value"] == "1"
        assert res_zero["is_significant_alpha_0_05"] is False

        # Symmetric discordance
        res_sym = compute_mcnemar_exact(10, 10)
        assert res_sym["total_discordant"] == 20
        assert res_sym["chi2"] == "0"
        assert res_sym["is_significant_alpha_0_05"] is False

        # Asymmetric discordance
        res_asym = compute_mcnemar_exact(30, 0)
        assert res_asym["total_discordant"] == 30
        assert res_asym["chi2"] == "30"
        assert res_asym["is_significant_alpha_0_05"] is True

    def test_remove_distractor_spans(self):
        """Verifies distractor removal from prompt text."""
        prompt = "Vertices: A, B. [Observer: Fluff text 99.] Relation: A->B is 5."
        spans = [(16, 42)]  # "[Observer: Fluff text 99.]"
        cleaned = remove_distractor_spans(prompt, spans)
        assert "Fluff text" not in cleaned
        assert "Vertices: A, B. " in cleaned
        assert "Relation: A->B is 5." in cleaned

    def test_parse_neural_output_variants(self):
        """Verifies output parsing from model generated markdown, JSON, or text."""
        # Clean JSON in code block
        text_codeblock = (
            '```json\n{"status": "SOLVED", "kind": "verdict", "answer": "CONSISTENT"}\n```'
        )
        res1 = parse_neural_output(text_codeblock, kind="verdict")
        assert res1["status"] == "SOLVED"
        assert res1["answer"] == "CONSISTENT"

        # Raw JSON
        text_raw = '{"status": "SOLVED", "kind": "verdict", "answer": "CONTRADICTION"}'
        res2 = parse_neural_output(text_raw, kind="verdict")
        assert res2["status"] == "SOLVED"
        assert res2["answer"] == "CONTRADICTION"

        # Prose keywords do not supply a certificate.
        text_heuristic = "Based on analysis, the system exhibits CONTRADICTION along a cycle."
        res3 = parse_neural_output(text_heuristic, kind="verdict")
        assert res3["status"] == "UNKNOWN"

        # Unparseable fallback
        text_unparseable = "I cannot determine whether this system has a potential."
        res4 = parse_neural_output(text_unparseable, kind="verdict")
        assert res4["status"] == "UNKNOWN"
        assert res4["refusal"] == "UNPARSEABLE_OUTPUT"

    @pytest.mark.skipif(
        torch is None or not DEFAULT_LOCAL_SNAPSHOT.is_dir(),
        reason="Requires local torch and model snapshot",
    )
    def test_single_case_physical_neural_execution_and_validity_gate(self):
        """Executes physical neural inference on 1 case and verifies validity gate and attention zeroing."""
        model, tokenizer, _src = get_or_load_neural_model()
        case = generate_case(kind="verdict", n_items=6, n_relations=7, seed=42)

        trace = run_single_neural_case(case, model, tokenizer, max_new_tokens=15)

        # 1. Validity gate: F-null MUST reproduce Arm A output token IDs identically
        assert trace["f_null_matches_a"] is True, "Validity gate failed: F-null did not match Arm A"

        # 2. Output token recording: actual tokens generated by physical neural model
        assert len(trace["arm_a"]["output_tokens"]) > 0
        assert len(trace["arm_f_distractor"]["output_tokens"]) > 0
        assert len(trace["arm_f_delete"]["output_tokens"]) > 0

        # 3. Fluff positions resolved
        assert trace["fluff_positions_count"] > 0

        # 4. Mechanism-level attention zeroing
        if trace["is_masking_authorized"]:
            assert trace["fluff_mass_masked"] < 1e-5, (
                f"Fluff attention mass not zeroed: {trace['fluff_mass_masked']}"
            )

    @pytest.mark.skipif(
        torch is None or not DEFAULT_LOCAL_SNAPSHOT.is_dir(),
        reason="Requires local torch and model snapshot",
    )
    def test_empirical_mcnemar_evaluation_report_structure(self):
        """Verifies report structure, Claim Discipline, and artifact generation on 2 cases."""
        rep = run_empirical_neural_mcnemar_evaluation(n_cases=2, base_seed=2026, max_new_tokens=15)

        assert rep["is_empirical_measurement"] is True
        assert rep["is_synthetic_fixture"] is False
        assert rep["sample_size"] == 2
        assert rep["validity_gate"]["gate_status"] == "PASSED"

        # McNemar structure
        f_vs_a = rep["comparison_F_distractor_vs_Arm_A"]
        assert "table_2x2" in f_vs_a
        assert "mcnemar" in f_vs_a

        # Claim Hygiene: 4 parts present, zero hype verbs
        cd = rep["claim_discipline"]
        assert len(cd["supports"]) > 0
        assert len(cd["does_not_support"]) > 0
        assert len(cd["narrowest_defensible_claim"]) > 0
        assert len(cd["next_test_needed"]) > 0

        all_text = " ".join(
            cd["supports"]
            + cd["does_not_support"]
            + [cd["narrowest_defensible_claim"], cd["next_test_needed"]]
        ).lower()
        forbidden = [
            "proves",
            "guarantees",
            "mathematically verifies",
            "fundamentally",
            "universal",
            "flawless",
            "obviously",
        ]
        for verb in forbidden:
            assert verb not in all_text, (
                f"Forbidden hype verb '{verb}' detected in claim discipline"
            )
