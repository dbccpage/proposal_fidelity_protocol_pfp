def __getattr__(name):
    if name.startswith("_"):
        raise AttributeError(name)
    if name in _PFP_EXPORTS:
        module_path, attribute = _PFP_EXPORTS[name]
        value = getattr(importlib.import_module(module_path, __name__), attribute)
        globals()[name] = value
        return value
    for submodule in reversed(_DOWNSTREAM_MODULES):
        try:
            module = importlib.import_module(submodule, __name__)
        except ImportError:
            continue
        if name in vars(module) and (not hasattr(module, "__all__") or name in module.__all__):
            value = vars(module)[name]
            globals()[name] = value
            return value
    raise AttributeError(name)


