"""
L1 Sparsity Regularization and Conversational Fluff Excision Benchmark for Paper 032.

This module evaluates the operational behavior of LLMs at the Layer 2 (decode-time)
perch under two conditions:
  Condition A: Unconstrained L2 Perch (Dense Natural Language / Chain-of-Thought)
  Condition B: Symbol Game L2 Perch (Fenced Support Simplex Delta(K) and Closed Ops)

It measures across 50 held-out discrete algebraic/topological rewrite tasks:
1. Token Support (L_0 norm) and Compression Ratio rho = ||y_dense||_0 / ||y_sparse||_0
2. Conversational Bullshit / Fluff Excision Rate (preamble, pleasantries, flattery, hedging)
3. Unpriced Rewrite Density delta_unpriced = count(unpriced steps) / count(total steps)
4. Deterministic Layer 3 Host Replay Success Rate in O(K) host time
5. Closed Refusal Firewall Accuracy (FW-CARRIER, FW-OP, FW-MOVE, F-04 ONTOLOGY_SMUGGLING)
"""

