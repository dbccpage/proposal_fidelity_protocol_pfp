"""Which evidence components exist.  A clause that needs a missing component
is never graded as if it existed; the row names what is missing.

Python components exist when their file does.  Lean components exist only
when the committed axiom report (``lean/axioms.txt``, regenerated by the
gate from a real build) lists their declarations within the axiom policy.

AuthorityEffect: None
"""

from __future__ import annotations

from pathlib import Path

from operations.domain.level_engine_context import (
    current_context,
)
from pfp.domain.lean_bridge.models import STANDARD_LEAN_AXIOMS

ROOT = current_context().runtime_root
POLICY = frozenset(STANDARD_LEAN_AXIOMS)
LEAN_REPORT = "lean/axioms.txt"

# component id -> the file that provides it
ENGINE_ROOT = Path(__file__).parent

# component id -> the file that provides it
COMPONENTS: dict[str, str] = {
    "py.exact.q": "exact/q.py",
    "py.exact.qi": "exact/qi.py",
    "py.exact.alg": "exact/alg.py",
    "py.exact.linalg": "exact/linalg.py",
    "py.exact.digest": "exact/digest.py",
}

# component id -> the declarations that must be reported within the policy
LEAN_COMPONENTS: dict[str, tuple[str, ...]] = {
    "lean.exact.qn": tuple(
        f"ExactRat.QN.{n}"
        for n in (
            "instDecidableEq", "add_comm", "add_assoc", "zero_add", "neg_add_cancel", "mul_comm",
            "mul_assoc", "one_mul", "mul_add", "zero_ne_one", "mul_inv_cancel", "pos_add", "pos_mul",
            "trichotomy", "not_pos_and_pos_neg",
        )
    ),
    # Claims for every natural from a start, by induction (round P6).
    "lean.exact.induction": tuple(
        f"ExactRat.QN.{n}" for n in ("eval_diff", "nonneg_from", "pos_from", "eval_reverse", "halving_bound")
    ),
}


def lean_report(root: Path = ROOT) -> dict[str, tuple[str, ...]]:
    """The committed axiom report, or nothing when it is absent."""
    path = current_context().lean_path("axioms.txt") if root == ROOT else root / LEAN_REPORT
    if not path.is_file():
        return {}
    out: dict[str, tuple[str, ...]] = {}
    for line in path.read_text(encoding="ascii").splitlines():
        name, _, rest = line.partition(": ")
        out[name] = () if rest == "(none)" else tuple(a.strip() for a in rest.split(","))
    return out


def within_policy(report: dict[str, tuple[str, ...]], name: str) -> bool:
    return name in report and set(report[name]) <= POLICY


def available(root: Path = ROOT) -> frozenset[str]:
    have = {c for c, p in COMPONENTS.items() if (root / p).is_file() or (ENGINE_ROOT / p).is_file()}
    report = lean_report(root)
    have |= {c for c, names in LEAN_COMPONENTS.items() if all(within_policy(report, n) for n in names)}
    return frozenset(have)
