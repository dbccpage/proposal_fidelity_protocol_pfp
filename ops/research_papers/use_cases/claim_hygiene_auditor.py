"""Claim Hygiene and Epistemic Dialect Firewall Auditor.

Enforces strict claim discipline per user_global and glossa-claim-hygiene-linter:
- Flags forbidden hype words (proves, guarantees, universal, flawless, etc.)
- Enforces replacement defaults (shows in this model, supports)
- Requires explicit bounding on empirical / toy model claims
- Asserts AuthorityEffect: None
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from typing import List, Tuple

FORBIDDEN_HYPE_WORDS: Tuple[str, ...] = (
    "proves",
    "guarantees",
    "mathematically verifies",
    "fundamentally",
    "true intelligence",
    "impossible",
    "universal",
    "flawless",
    "perfectly",
    "clearly",
    "obviously",
    "simply",
    "merely",
    "weaponized",
)


@dataclass(frozen=True)
class ClaimViolation:
    """A detected violation of claim discipline."""

    line_number: int
    matched_word: str
    suggested_replacement: str
    context_snippet: str


@dataclass(frozen=True)
class ClaimHygieneReport:
    """Report generated by the Claim Hygiene Auditor."""

    passed: bool
    violations: Tuple[ClaimViolation, ...]
    total_violations: int
    authority_effect: str = "None"

    def __post_init__(self) -> None:
        if self.authority_effect != "None":
            raise ValueError("AuthorityEffect must be 'None'")


class ClaimHygieneAuditor:
    """Audits monograph prose and claim records for forbidden hype words."""

    REPLACEMENTS = {
        "proves": "shows in this model / supports",
        "guarantees": "guarantees under declared assumptions",
        "mathematically verifies": "checked by this oracle/test",
        "fundamentally": "structurally",
        "universal": "carrier-scoped",
        "flawless": "verified against declared predicates",
        "perfectly": "consistently within tolerances",
        "clearly": "by inspection",
        "obviously": "as formulated",
        "simply": "directly",
        "merely": "strictly",
    }

    AUTHORIZED_PROPER_NOUNS: Tuple[str, ...] = (
        "meta & universal re-presentation",
        "universal re-presentation",
        "meta \\& universal re-presentation",
    )

    @classmethod
    def audit_text(cls, text: str) -> ClaimHygieneReport:
        lines = text.splitlines()
        violations: List[ClaimViolation] = []

        for idx, line in enumerate(lines):
            line_lower = line.lower()
            sanitized_line = line_lower
            for phrase in cls.AUTHORIZED_PROPER_NOUNS:
                sanitized_line = sanitized_line.replace(phrase, " " * len(phrase))

            for word in FORBIDDEN_HYPE_WORDS:
                pattern = rf"\b{re.escape(word)}\b"
                if re.search(pattern, sanitized_line):
                    replacement = cls.REPLACEMENTS.get(word, "qualified / bounded claim")
                    violations.append(
                        ClaimViolation(
                            line_number=idx + 1,
                            matched_word=word,
                            suggested_replacement=replacement,
                            context_snippet=line.strip()[:100],
                        )
                    )

        passed = len(violations) == 0
        return ClaimHygieneReport(
            passed=passed,
            violations=tuple(violations),
            total_violations=len(violations),
            authority_effect="None",
        )
