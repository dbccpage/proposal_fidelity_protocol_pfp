"""Lean source text for exact values: the shared writer the level
certificates use.  Every value is written as ``QN.ofPair num den``, so the
kernel reads exactly the rational the Python engine computed with.

AuthorityEffect: None
"""

from __future__ import annotations

from collections.abc import Sequence

from .exact.q import Q


def q(x: Q) -> str:
    return f"QN.ofPair ({x.num}) {x.den}"


def row(xs: Sequence[Q]) -> str:
    return "[" + ", ".join(q(x) for x in xs) + "]"


def mat(rows: Sequence[Sequence[Q]]) -> str:
    return "[" + ",\n    ".join(row(r) for r in rows) + "]"


def header(module: str, title: str, body: Sequence[str]) -> list[str]:
    """The opening of a generated certificate module."""
    return [
        "import ExactRat",
        "",
        "/-!",
        f"# {title}",
        "",
        "Generated by `tools/lean_gen.py` from the fixtures; do not edit. Each theorem",
        "states the verdict the Python engine computed, and `decide` re-checks it with",
        "the exact-rational library.",
        "",
        "AuthorityEffect: None",
        "-/",
        "",
        f"namespace {module}",
        "",
        "open ExactRat",
        "",
        *body,
    ]
