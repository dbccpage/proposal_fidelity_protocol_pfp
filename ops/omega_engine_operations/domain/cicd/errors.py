"""Domain error catalog and exceptions for local_ci Bounded Context."""

from __future__ import annotations

from enum import Enum


class LocalCiReceiptErrorCode(str, Enum):
    """Stable refusal codes emitted by the protocol."""

    BYTES_REQUIRED = "BYTES_REQUIRED"
    UTF8_BOM_FORBIDDEN = "UTF8_BOM_FORBIDDEN"
    CARRIAGE_RETURN_FORBIDDEN = "CARRIAGE_RETURN_FORBIDDEN"
    INPUT_TOO_LARGE = "INPUT_TOO_LARGE"
    INVALID_UTF8 = "INVALID_UTF8"
    INVALID_JSON = "INVALID_JSON"
    DUPLICATE_KEY = "DUPLICATE_KEY"
    FLOAT_FORBIDDEN = "FLOAT_FORBIDDEN"
    NONFINITE_FORBIDDEN = "NONFINITE_FORBIDDEN"
    JSON_DEPTH_LIMIT = "JSON_DEPTH_LIMIT"
    JSON_NODE_LIMIT = "JSON_NODE_LIMIT"
    NON_SCALAR_UNICODE = "NON_SCALAR_UNICODE"
    NON_NFC_STRING = "NON_NFC_STRING"
    NON_CANONICAL_BYTES = "NON_CANONICAL_BYTES"
    INTEGER_LEXEME_TOO_LONG = "INTEGER_LEXEME_TOO_LONG"
    INVALID_RECORD = "INVALID_RECORD"
    UNSUPPORTED_RECORD = "UNSUPPORTED_RECORD"
    IO_ERROR = "IO_ERROR"
    EMPTY_RESULTS = "EMPTY_RESULTS"
    MALFORMED_RESULT = "MALFORMED_RESULT"
    DUPLICATE_RESULT = "DUPLICATE_RESULT"
    UNKNOWN_RESULT = "UNKNOWN_RESULT"
    QUARANTINED_GATE_EXECUTED = "QUARANTINED_GATE_EXECUTED"
    MISSING_RESULT = "MISSING_RESULT"
    RESULT_ORDER_MISMATCH = "RESULT_ORDER_MISMATCH"
    RESULT_BINDING_MISMATCH = "RESULT_BINDING_MISMATCH"
    DURATION_OUT_OF_BOUNDS = "DURATION_OUT_OF_BOUNDS"
    REQUIRED_GATE_NONPASS = "REQUIRED_GATE_NONPASS"
    SKIP_OR_BYPASS_REFUSED = "SKIP_OR_BYPASS_REFUSED"
    RECEIPT_BINDING_MISMATCH = "RECEIPT_BINDING_MISMATCH"
    RECEIPT_DERIVATION_MISMATCH = "RECEIPT_DERIVATION_MISMATCH"
    QUARANTINED_ROUTE = "QUARANTINED_ROUTE"
    VERIFIER_ADAPTER_UNAVAILABLE = "VERIFIER_ADAPTER_UNAVAILABLE"
    INVALID_PATH = "INVALID_PATH"
    REPARSE_POINT_REFUSED = "REPARSE_POINT_REFUSED"


class LocalCiReceiptError(ValueError):
    """A typed refusal to construct, parse, or verify a local-CI receipt."""

    def __init__(self, code: LocalCiReceiptErrorCode, message: str) -> None:
        self.code = code
        self.message = message
        super().__init__(f"{code.value}: {message}")
