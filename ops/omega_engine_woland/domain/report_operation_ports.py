"""Ports for native report checking and durable episode custody."""
from typing import Protocol

from omega_engine_operations.domain.rop.result import Result


class ReportOperationPort(Protocol):
    def identity(self) -> str: ...
    def invoke(self, action: str, payload: dict) -> Result: ...


class ReportEpisodePort(Protocol):
    def reserve(self, episode: str, bundle: dict, allowance: int) -> int: ...
    def claim(self, episode: str, attempt: int) -> dict: ...
    def finish(self, episode: str, attempt: int, evidence: dict, candidate: dict | None) -> bool: ...
