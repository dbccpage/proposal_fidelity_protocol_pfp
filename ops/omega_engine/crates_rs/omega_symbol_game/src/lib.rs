#[derive(Debug, Clone, PartialEq, Eq)]
pub enum EnvelopeError {
    Effect,
    Schema,
    Hex,
}

impl std::fmt::Display for EnvelopeError {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(formatter, "{:?}", self)
    }
}

impl std::error::Error for EnvelopeError {}

/// A laboratory host outcome: effect None, a three-part schema, and a 32-byte packet.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct LaboratoryOutcomeEnvelope {
    schema: [u16; 3],
    packet: [u8; 32],
}

fn schema_component(text: &str) -> Result<u16, EnvelopeError> {
    if text.is_empty() || (text.len() > 1 && text.starts_with("0")) {
        return Err(EnvelopeError::Schema);
    }
    if !text.bytes().all(|byte| byte.is_ascii_digit()) {
        return Err(EnvelopeError::Schema);
    }
    text.parse::<u16>().map_err(|_| EnvelopeError::Schema)
}

fn decode_hex_pair(pair: &[u8]) -> Option<u8> {
    let high = char::from(*pair.first()?).to_digit(16)?;
    let low = char::from(*pair.get(1)?).to_digit(16)?;
    u8::try_from(high * 16 + low).ok()
}

fn decode_hex_byte(text: &str) -> Result<[u8; 32], EnvelopeError> {
    if text.len() != 64 {
        return Err(EnvelopeError::Hex);
    }
    let mut packet = [0u8; 32];
    for (slot, pair) in packet.iter_mut().zip(text.as_bytes().chunks_exact(2)) {
        *slot = decode_hex_pair(pair).ok_or(EnvelopeError::Hex)?;
    }
    Ok(packet)
}

impl LaboratoryOutcomeEnvelope {
    pub fn try_parse(effect: &str, schema: &str, packet_hex: &str) -> Result<Self, EnvelopeError> {
        if effect != "None" {
            return Err(EnvelopeError::Effect);
        }
        let mut parts = schema.split(".");
        let major = schema_component(parts.next().ok_or(EnvelopeError::Schema)?)?;
        let minor = schema_component(parts.next().ok_or(EnvelopeError::Schema)?)?;
        let patch = schema_component(parts.next().ok_or(EnvelopeError::Schema)?)?;
        if parts.next().is_some() {
            return Err(EnvelopeError::Schema);
        }
        Ok(Self { schema: [major, minor, patch], packet: decode_hex_byte(packet_hex)? })
    }

    pub fn schema(&self) -> [u16; 3] { self.schema }
    pub fn packet(&self) -> &[u8; 32] { &self.packet }
}

#[cfg(test)]
mod envelope_tests {
    use super::*;

    #[test]
    fn a_none_effect_decodes_a_zero_packet() {
        let hex = "0".repeat(64);
        let envelope = LaboratoryOutcomeEnvelope::try_parse("None", "1.2.3", &hex);
        assert!(matches!(envelope, Ok(ref envelope) if envelope.schema() == [1, 2, 3] && envelope.packet()[0] == 0));
    }

    #[test]
    fn a_leading_zero_schema_component_is_refused() {
        let hex = "0".repeat(64);
        let envelope = LaboratoryOutcomeEnvelope::try_parse("None", "01.2.3", &hex);
        assert!(matches!(envelope, Err(EnvelopeError::Schema)));
    }
}
